# uint32_t regs_hold(uint32_t ticks, const uint64_t *patterns, uint64_t *out)
# Loads patterns[0..24] into r6-r10, r12, r14-r31 and r11, spins until the time base has moved ticks, using only r0
# and r3-r5, then stores those registers into out[0..24] in the same order and returns the loop's count. Saves and
# restores r14-r31.
	.text
	.globl regs_hold
	.type regs_hold, @function
regs_hold:
	stwu r1, -160(r1)
	std r14, 8(r1)
	std r15, 16(r1)
	std r16, 24(r1)
	std r17, 32(r1)
	std r18, 40(r1)
	std r19, 48(r1)
	std r20, 56(r1)
	std r21, 64(r1)
	std r22, 72(r1)
	std r23, 80(r1)
	std r24, 88(r1)
	std r25, 96(r1)
	std r26, 104(r1)
	std r27, 112(r1)
	std r28, 120(r1)
	std r29, 128(r1)
	std r30, 136(r1)
	std r31, 144(r1)
	stw r5, 152(r1)
	mr r0, r3
	mr r11, r4
	ld r6, 0(r11)
	ld r7, 8(r11)
	ld r8, 16(r11)
	ld r9, 24(r11)
	ld r10, 32(r11)
	ld r12, 40(r11)
	ld r14, 48(r11)
	ld r15, 56(r11)
	ld r16, 64(r11)
	ld r17, 72(r11)
	ld r18, 80(r11)
	ld r19, 88(r11)
	ld r20, 96(r11)
	ld r21, 104(r11)
	ld r22, 112(r11)
	ld r23, 120(r11)
	ld r24, 128(r11)
	ld r25, 136(r11)
	ld r26, 144(r11)
	ld r27, 152(r11)
	ld r28, 160(r11)
	ld r29, 168(r11)
	ld r30, 176(r11)
	ld r31, 184(r11)
	ld r11, 192(r11)
	mftb r4
	li r3, 0
1:	addi r3, r3, 1
	mftb r5
	subf r5, r4, r5
	cmplw r5, r0
	blt 1b
	lwz r5, 152(r1)
	std r6, 0(r5)
	std r7, 8(r5)
	std r8, 16(r5)
	std r9, 24(r5)
	std r10, 32(r5)
	std r12, 40(r5)
	std r14, 48(r5)
	std r15, 56(r5)
	std r16, 64(r5)
	std r17, 72(r5)
	std r18, 80(r5)
	std r19, 88(r5)
	std r20, 96(r5)
	std r21, 104(r5)
	std r22, 112(r5)
	std r23, 120(r5)
	std r24, 128(r5)
	std r25, 136(r5)
	std r26, 144(r5)
	std r27, 152(r5)
	std r28, 160(r5)
	std r29, 168(r5)
	std r30, 176(r5)
	std r31, 184(r5)
	std r11, 192(r5)
	ld r14, 8(r1)
	ld r15, 16(r1)
	ld r16, 24(r1)
	ld r17, 32(r1)
	ld r18, 40(r1)
	ld r19, 48(r1)
	ld r20, 56(r1)
	ld r21, 64(r1)
	ld r22, 72(r1)
	ld r23, 80(r1)
	ld r24, 88(r1)
	ld r25, 96(r1)
	ld r26, 104(r1)
	ld r27, 112(r1)
	ld r28, 120(r1)
	ld r29, 128(r1)
	ld r30, 136(r1)
	ld r31, 144(r1)
	addi r1, r1, 160
	blr
	.size regs_hold, .-regs_hold
