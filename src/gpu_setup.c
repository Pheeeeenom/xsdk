void xsdk_gpu_put_window(GpuPackets *packets, uint32_t width, uint32_t height)
{
	const uint32_t window[] = { 0, 0, width | height << 16 };
	gpu_put_registers(packets, PA_SC_WINDOW_OFFSET, window, 3);
}

// Whole pages, as libxenon invalidates (xe.c:766, 1871); 192 bytes left the vertex cache stale (docs/HARDWARE.md).
void xsdk_gpu_put_coherency(GpuPackets *packets, uint32_t actions, uint32_t base, uint32_t size_bytes)
{
	const uint32_t first = base & ~(COHER_PAGE_BYTES - 1);
	const uint32_t end = (base + size_bytes + COHER_PAGE_BYTES - 1) & ~(COHER_PAGE_BYTES - 1);
	const uint32_t range[] = { end - first, first };
	gpu_put_register(packets, COHER_STATUS_HOST, actions);
	gpu_put_registers(packets, COHER_SIZE_HOST, range, 2);
	gpu_put_type3(packets, PM4_WAIT_REG_MEM, 5);
	gpu_put(packets, WAIT_REG_MEM_EQUAL);
	gpu_put(packets, COHER_STATUS_HOST);
	gpu_put(packets, 0);
	gpu_put(packets, COHER_BUSY);
	gpu_put(packets, WAIT_REG_MEM_INTERVAL);
}

// The ME_INIT that starts Xe_pGInit (xe.c:556-561).
static void put_me_init(GpuPackets *packets)
{
	static const uint32_t payload[] = {
		0x000003FF,
		0,
		0,
		0,
		0x80,
		0x100,
		0x180,
		0x200,
		0x280,
		0x300,
		0x380,
		0x00010800,
		7,
		0,
		0,
		0,
		0,
		0,
	};
	gpu_put_type3(packets, PM4_ME_INIT, sizeof payload / 4);
	for (uint32_t i = 0; i < sizeof payload / 4; i++)
		gpu_put(packets, payload[i]);
}

// The counter xsdk_gpu_write_clock copies, from 0; XAM leaves it off (docs/HARDWARE.md, "A clock the GPU and the CPU
// both read"). Only at set-up, as a reset later would take the clock back.
static void put_clock(GpuPackets *packets)
{
	gpu_put_register(packets, CP_PERFMON_CNTL, PERF_STATE_RESET);
	gpu_put_register(packets, RBBM_PERFCOUNTER1_SELECT, RBBM1_COUNT);
	gpu_put_register(packets, CP_PERFMON_CNTL, PERF_STATE_ENABLE);
}

// Xe_pGInit4 and Xe_pGInit5; UNKNOWN_0A02-0A05 and the scratch writes are left out (xe.c:464-498).
static void put_shader_unit(GpuPackets *packets)
{
	gpu_put_register(packets, SQ_INST_STORE_MANAGMENT, 0x00010800);
	gpu_put_register(packets, WAIT_UNTIL, WAIT_3D_IDLE_CLEAN);
	gpu_put_register(packets, SQ_EO_RT, 0);
	gpu_put_register(packets, SQ_FLOW_CONTROL, 0x04000000);
	gpu_put_type3(packets, PM4_REG_RMW, 3);
	gpu_put(packets, UNKNOWN_0081);
	gpu_put(packets, 0xFFFFFFFF);
	gpu_put(packets, 0x80010000);
	gpu_put_type3(packets, PM4_REG_RMW, 3);
	gpu_put(packets, UNKNOWN_0082);
	gpu_put(packets, 0xFFFFFFFF);
	gpu_put(packets, 0);
	gpu_put_register(packets, UNKNOWN_0E42, 0x1F60);
	gpu_put_register(packets, PA_CL_ENHANCE, 3);
}

// Xe_pGInit6, Xe_pGInit10 and Xe_pGInit7, less the scratch writes (xe.c:500-515, 540-552).
static void put_render_backend(GpuPackets *packets)
{
	xsdk_gpu_put_window(packets, 1024, 720);
	xsdk_gpu_put_window(packets, 1024, 720);
	gpu_put_type3(packets, PM4_INVALIDATE_STATE, 1);
	gpu_put(packets, INVALIDATE_SHADERS);
	gpu_put_register(packets, WAIT_UNTIL, WAIT_3D_IDLE_CLEAN);
	gpu_put_register(packets, RB_BC_CONTROL, 0x0000200E);
}

static void put_shader(GpuPackets *packets, uint32_t type, const uint32_t *shader, uint32_t dword_count)
{
	gpu_put_type3(packets, PM4_IM_LOAD_IMMEDIATE, 2 + dword_count);
	gpu_put(packets, type);
	gpu_put(packets, dword_count);
	for (uint32_t i = 0; i < dword_count; i++)
		gpu_put(packets, shader[i]);
}

// Xe_pGInit0: a vertex and a pixel shader, and draw state (xe.c:398-441).
static void put_draw_state(GpuPackets *packets)
{
	const uint32_t program[] = { 0x1000000E, 0 };
	const uint32_t indices[] = { 0xFFFF, 0, 0 };
	const uint32_t clip[] = { CLIP_DISABLE, VTX_WINDOW_OFFSET_ENABLE, VTE_XY_Z_ALREADY_TRANSFORMED };
	gpu_put_type3(packets, PM4_INVALIDATE_STATE, 1);
	gpu_put(packets, INVALIDATE_SHADERS);
	put_shader(packets, SHADER_TYPE_VERTEX, setup_vertex_shader, sizeof setup_vertex_shader / 4);
	put_shader(packets, SHADER_TYPE_PIXEL, setup_pixel_shader, sizeof setup_pixel_shader / 4);
	gpu_put_registers(packets, SQ_PROGRAM_CNTL, program, 2);
	gpu_put_registers(packets, VGT_MAX_VTX_INDX, indices, 3);
	gpu_put_registers(packets, PA_CL_CLIP_CNTL, clip, 3);
	gpu_put_register(packets, PA_SC_AA_MASK, 0xFFFF);
	gpu_put_register(packets, COHER_DEST_BASE_7, 0);
	gpu_put_register(packets, RB_DEPTHCONTROL, 0);
	gpu_put_register(packets, RB_HIZCONTROL, 0);
	gpu_put_register(packets, RB_MODECONTROL, EDRAM_MODE_COLOR_DEPTH);
	gpu_put_register(packets, RB_COLOR_MASK, 0);
	gpu_put_register(packets, PA_SU_POINT_SIZE, 0x00080008);
	gpu_put_register(packets, PA_SU_VTX_CNTL, PIX_CENTER_D3D);
	xsdk_gpu_put_window(packets, 16, 16);
}

// Xe_pGInit1 stepping the shader unit's register split (xe.c:443-452, 527-528): vertex shaders' share in bits 12-19
// and pixel shaders' in bits 4-11 (Linux:drivers/gpu/drm/msm/registers/adreno/a2xx.xml:1231-1235). libxenon steps on
// to 0x70, leaving pixel shaders 16 registers, and a pixel shader past its share hangs the GPU; the steps stop at the
// kernel's own 0x40, 64 and 64 (docs/HARDWARE.md, "libxenon's set-up makes the resolves work"), which xost's builds
// for xsdk assume (xost:xasm/program.py, XSDK_REGISTERS).
static void put_register_split(GpuPackets *packets)
{
	for (uint32_t i = REGISTER_SPLIT_FIRST; i <= REGISTER_SPLIT_LAST; i++) {
		const uint32_t split = i << 12 | (REGISTER_SPLIT_TOTAL - i) << 4;
		gpu_put_register(packets, WAIT_UNTIL, WAIT_3D_IDLE_CLEAN);
		gpu_put_register_repeated(packets, SQ_GPR_MANAGEMENT, split | 1, 8);
		gpu_put_register(packets, SQ_GPR_MANAGEMENT, split);
	}
}

// Xe_pGInit2 and Xe_pGInit8: 24 one-point draws, then the window again (xe.c:454-462, 517-520).
static void put_point_draws(GpuPackets *packets)
{
	for (uint32_t i = 0; i < POINT_DRAWS; i++) {
		gpu_put_type3(packets, PM4_DRAW_INDX_2, 1);
		gpu_put(packets, POINT_LIST_AUTO_INDEX_1);
	}
	xsdk_gpu_put_window(packets, 1024, 720);
}

// Everything after the ME_INIT.
static void put_state(GpuPackets *packets)
{
	put_shader_unit(packets);
	put_render_backend(packets);
	put_draw_state(packets);
	put_register_split(packets);
	put_point_draws(packets);
	// Xe_Init invalidates the vertex cache over all memory last (xe.c:992).
	xsdk_gpu_put_coherency(packets, COHER_VERTEX_CACHE, 0, ALL_MEMORY_BYTES);
	// libxenon leaves this at its reset value; D3D keeps it whole (xenia:src/xenia/gpu/draw_util.cc:575-576).
	const uint32_t screen[] = { 0, SCREEN_SCISSOR_8192 };
	gpu_put_registers(packets, PA_SC_SCREEN_SCISSOR_TL, screen, 2);
	// The split libxenon's constant setters assume, vertex shaders' 256 then pixel shaders' (xe.c:2013-2029).
	const uint32_t constant_split[] = { VS_CONSTANTS_FROM_0, PS_CONSTANTS_FROM_256 };
	gpu_put_registers(packets, SQ_VS_CONST, constant_split, 2);
}

void xsdk_gpu_set_up(void)
{
	for (uint32_t i = 0; i < sizeof saved_registers / sizeof saved_registers[0]; i++)
		saved_values[i] = gpu_registers[saved_registers[i]];
	GpuPackets packets = { .dwords = set_up_dwords, .count = 0, .capacity = SET_UP_MAX_DWORDS };
	put_me_init(&packets);
	put_clock(&packets);
	put_state(&packets);
	xsdk_gpu_write(&packets);
	xsdk_gpu_forget_shaders();
}

void xsdk_gpu_set_up_again(void)
{
	GpuPackets packets = { .dwords = set_up_dwords, .count = 0, .capacity = SET_UP_MAX_DWORDS };
	put_state(&packets);
	xsdk_gpu_write(&packets);
	xsdk_gpu_forget_shaders();
}

void xsdk_gpu_put_back(void)
{
	uint32_t dwords[PUT_BACK_MAX_DWORDS];
	GpuPackets packets = { .dwords = dwords, .count = 0, .capacity = PUT_BACK_MAX_DWORDS };
	gpu_put_register(&packets, WAIT_UNTIL, WAIT_3D_IDLE_CLEAN);
	for (uint32_t i = 0; i < sizeof saved_registers / sizeof saved_registers[0]; i++)
		gpu_put_register(&packets, saved_registers[i], saved_values[i]);
	xsdk_gpu_write(&packets);
}
