#include "xsdk/gpu.h"

#include <assert.h>
#include <stdint.h>

#include "gpu_private.h"

enum {
	RESOLVE_MAX_DWORDS = 128,
	// eDRAM tiles without multisampling (xenia:src/xenia/gpu/xenos.h:414-416).
	TILE_WIDTH = 80,
	TILE_HEIGHT = 16,
	EDRAM_TILES = 2048,
	// The size libxenon invalidates for its vertex pool: 12000 bytes and a page (xe.c:33, 1850, 1871).
	RECTANGLE_INVALIDATE_BYTES = 12000 + 0x1000,
	INVALIDATE_VERTEX_SHADER = 1 << 8,
	COHER_RESOLVE_ACTIONS = 0x03000100,
	CACHE_FLUSH = 6,
	// A three-vertex rectangle list, auto-indexed (xenia:src/xenia/gpu/registers.h:311).
	RECTANGLE_LIST_AUTO_INDEX_3 = 8 | 2 << 6 | 3 << 16,
	CLIP_DISABLE = 1 << 16,
	VTX_WINDOW_OFFSET_ENABLE = 1 << 16,
	VTE_XY_Z_ALREADY_TRANSFORMED = 0x300,
	EDRAM_MODE_COPY = 6,
	// Copy colour, clear colour and depth, k_8_8_8_8 with the swap bit (xe.c:1104-1108).
	COPY_CONTROL_CLEAR_COLOR_DEPTH = 1 << 20 | 3 << 8,
	COPY_DEST_INFO_8888_SWAP = 1 << 24 | 6 << 7,
	DEPTH_CLEAR_FAR = 0xFFFFFF00,
	DEPTH_STENCIL_ALWAYS_WRITE = 0x8777,
	PROGRAM_CNTL_RESOLVE = 2 | 1 << 16,
	VERTEX_FETCH_TYPE = 3,
	VERTEX_FETCH_SIZE_6_8IN32 = 1 << 28 | 6 << 2 | 2,
	// libxenon loads its 12-dword shader as 15, with three zeros after it.
	SHADER_PADDING_DWORDS = 3,
};

// Generated by tools/gen_resolve_vs.py.
static const uint32_t resolve_vertex_shader[] = {
	0x10011002,
	0x00001200,
	0xC4000000,
	0x00000000,
	0x1003C200,
	0x22000000,
	0x00080000,
	0x00253B48,
	0x00000002,
	0xC80F803E,
	0x00000000,
	0xC2000000,
};

// RB_COLOR_CLEAR wants the packed colour, red low (xenia:src/xenia/gpu/shaders/pixel_formats.xesli:113-116).
static uint32_t packed_8888(uint32_t argb)
{
	return (argb & 0xFF00FF00) | (argb >> 16 & 0xFF) | (argb & 0xFF) << 16;
}

static void put_shader(GpuPackets *packets)
{
	const uint32_t dword_count = sizeof resolve_vertex_shader / 4 + SHADER_PADDING_DWORDS;
	gpu_put_type3(packets, PM4_IM_LOAD_IMMEDIATE, 2 + dword_count);
	gpu_put(packets, SHADER_TYPE_VERTEX);
	gpu_put(packets, dword_count);
	for (uint32_t i = 0; i < dword_count; i++)
		gpu_put(packets, i < sizeof resolve_vertex_shader / 4 ? resolve_vertex_shader[i] : 0);
}

// Xe_ResolveInto, less its scratch write, with the layout Xe_SetRenderTarget gives the target (xe.c:998-1165).
void xsdk_gpu_resolve(uint32_t address, uint32_t width, uint32_t height, uint32_t clear_argb)
{
	assert(width % 32 == 0);
	// Depth first, then colour, each this many tiles, a whole even number of them across.
	const uint32_t tiles_across = ((width + TILE_WIDTH - 1) / TILE_WIDTH + 1) & ~1u;
	const uint32_t target_tiles = tiles_across * ((height + TILE_HEIGHT - 1) / TILE_HEIGHT);
	assert(2 * target_tiles <= EDRAM_TILES);
	const uint32_t edram_pitch = tiles_across * TILE_WIDTH;
	const uint32_t vertices = xsdk_gpu_rectangle(width, height);
	const uint32_t surface[] = { edram_pitch | edram_pitch << 18, target_tiles, 0 };
	const uint32_t viewport[] = { 0x44000000, 0x44000000, 0xC3B40000, 0x43B40000, 0x3F800000, 0 };
	const uint32_t copy[] = { COPY_CONTROL_CLEAR_COLOR_DEPTH, address, width | height << 16, COPY_DEST_INFO_8888_SWAP };
	const uint32_t program[] = { PROGRAM_CNTL_RESOLVE, 0 };
	const uint32_t indices[] = { 0xFFFF, 0, 0 };
	const uint32_t clip[] = { CLIP_DISABLE, VTX_WINDOW_OFFSET_ENABLE, VTE_XY_Z_ALREADY_TRANSFORMED };
	const uint32_t fetch[] = { vertices | VERTEX_FETCH_TYPE, VERTEX_FETCH_SIZE_6_8IN32, 0, 0, 0, 0 };
	const uint32_t flush_fetch[] = { 0, 0, 0 };
	uint32_t dwords[RESOLVE_MAX_DWORDS];
	GpuPackets packets = { .dwords = dwords, .count = 0, .capacity = RESOLVE_MAX_DWORDS };
	xsdk_gpu_put_window(&packets, width, height);
	xsdk_gpu_put_coherency(&packets, COHER_VERTEX_CACHE, vertices, RECTANGLE_INVALIDATE_BYTES);
	gpu_put_registers(&packets, RB_SURFACE_INFO, surface, 3);
	gpu_put_register(&packets, RB_COLOR_MASK, 0xF);
	gpu_put_registers(&packets, PA_CL_VPORT_XSCALE, viewport, 6);
	gpu_put_registers(&packets, RB_COPY_CONTROL, copy, 4);
	gpu_put_register(&packets, RB_DEPTH_CLEAR, DEPTH_CLEAR_FAR);
	gpu_put_register(&packets, RB_COLOR_CLEAR, packed_8888(clear_argb));
	gpu_put_register(&packets, RB_COLOR_CLEAR_LO, packed_8888(clear_argb));
	gpu_put_register(&packets, RB_MODECONTROL, EDRAM_MODE_COPY);
	gpu_put_register(&packets, RB_MODECONTROL, EDRAM_MODE_COPY);
	gpu_put_register(&packets, RB_DEPTHCONTROL, DEPTH_STENCIL_ALWAYS_WRITE);
	gpu_put_register(&packets, WAIT_UNTIL, WAIT_3D_IDLE_CLEAN);
	gpu_put_type3(&packets, PM4_INVALIDATE_STATE, 1);
	gpu_put(&packets, INVALIDATE_VERTEX_SHADER);
	put_shader(&packets);
	gpu_put_registers(&packets, SQ_PROGRAM_CNTL, program, 2);
	gpu_put_register(&packets, RB_HIZCONTROL, 0);
	gpu_put_registers(&packets, VGT_MAX_VTX_INDX, indices, 3);
	gpu_put_registers(&packets, PA_CL_CLIP_CNTL, clip, 3);
	gpu_put_register(&packets, PA_SC_AA_MASK, 0xFFFF);
	gpu_put_register(&packets, COHER_DEST_BASE_7, 0);
	gpu_put_registers(&packets, SHADER_CONSTANT_FETCH_00_0, fetch, 6);
	gpu_put_registers(&packets, SHADER_CONSTANT_FLUSH_FETCH_0, flush_fetch, 3);
	gpu_put_type3(&packets, PM4_DRAW_INDX_2, 1);
	gpu_put(&packets, RECTANGLE_LIST_AUTO_INDEX_3);
	gpu_put_type3(&packets, PM4_EVENT_WRITE, 1);
	gpu_put(&packets, CACHE_FLUSH);
	gpu_put_register(&packets, COHER_DEST_BASE_1, 0);
	xsdk_gpu_put_coherency(&packets, COHER_RESOLVE_ACTIONS, address, width * height * 4);
	gpu_put_register(&packets, RB_COPY_CONTROL, 0);
	gpu_put_register(&packets, RB_COPY_DEST_INFO, 0);
	// Xe_Sync's wait for idle (xe.c:1223-1226, 1278-1282).
	gpu_put_register(&packets, WAIT_UNTIL, WAIT_3D_IDLE_CLEAN);
	xsdk_gpu_write(&packets);
}
