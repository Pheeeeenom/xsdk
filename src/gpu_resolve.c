#include "xsdk/gpu.h"

#include <assert.h>
#include <stdint.h>

#include "gpu_private.h"

enum {
	RESOLVE_MAX_DWORDS = 160,
	// The size libxenon invalidates for its vertex pool: 12000 bytes and a page (xe.c:33, 1850, 1871).
	RECTANGLE_INVALIDATE_BYTES = 12000 + 0x1000,
	INVALIDATE_VERTEX_SHADER = 1 << 8,
	COHER_RESOLVE_ACTIONS = 0x03000100,
	CACHE_FLUSH = 6,
	// A three-vertex rectangle list, auto-indexed (xenia:src/xenia/gpu/registers.h:311).
	RECTANGLE_LIST_AUTO_INDEX_3 = 8 | 2 << 6 | 3 << 16,
	CLIP_DISABLE = 1 << 16,
	VTX_WINDOW_OFFSET_ENABLE = 1 << 16,
	VTE_XY_Z_ALREADY_TRANSFORMED = 0x300,
	// PA_CL_VTE_CNTL's vport_z_scale_ena and vport_z_offset_ena (xenia:src/xenia/gpu/registers.h:573-574).
	VTE_Z_SCALE_OFFSET = 3 << 4,
	// Depth only, which Xenia takes to skip the pixel shader (xenia:src/xenia/gpu/xenos.h:889-907).
	EDRAM_MODE_DEPTH_ONLY = 5,
	EDRAM_MODE_COPY = 6,
	// RB_DEPTHCONTROL's z_enable, compare never, no write (xenia:src/xenia/gpu/registers.h:799-805).
	DEPTH_TEST_NEVER = 1 << 1,
	// Copy colour into k_8_8_8_8, then clear colour or depth (xe.c:1104-1108).
	COPY_CONTROL_CONVERT = 1 << 20,
	COPY_SAMPLE_SELECT_SHIFT = 4,
	// RB_COPY_CONTROL's source: colour target 0, or depth (xenia:src/xenia/gpu/registers.h:856).
	COPY_SOURCE_COLOR_0 = 0,
	COPY_SOURCE_DEPTH = 4,
	COPY_DEST_INFO_8888 = 6 << 7,
	// RB_COPY_CONTROL's clears (xenia:src/xenia/gpu/registers.h:860-861).
	COPY_CONTROL_COLOR_CLEAR = 1 << 8,
	COPY_CONTROL_DEPTH_CLEAR = 1 << 9,
	// Swaps red and blue (xenia:src/xenia/gpu/shaders/resolve.xesli:768-795).
	COPY_DEST_SWAP = 1 << 24,
	COPY_DEST_INFO_8888_SWAP = COPY_DEST_INFO_8888 | COPY_DEST_SWAP,
	// libxenon's ARGB surfaces also swap each dword's bytes, its BGRA front buffer not (xe.c:968, 1104-1108; xe.h:181).
	COPY_DEST_ENDIAN_8IN32 = 2,
	// The depth above the stencil, as an eDRAM sample holds them
	// (xenia:src/xenia/gpu/dxbc_shader_translator_om.cc:978).
	DEPTH_CLEAR_FAR = 0xFFFFFF00,
	DEPTH_CLEAR_SHIFT = 8,
	// The hierarchical buffer holds depth in 2048ths: the top 11 bits of RB_DEPTH_CLEAR's (docs/HARDWARE.md).
	HIZ_CLEAR_SHIFT = 21,
	DEPTH_24_MAX = 0xFFFFFF,
	DEPTH_STENCIL_ALWAYS_WRITE = 0x8777,
	PROGRAM_CNTL_RESOLVE = 2 | 1 << 16,
	VERTEX_FETCH_TYPE = 3,
	VERTEX_FETCH_SIZE_6_8IN32 = 1 << 28 | 6 << 2 | 2,
	// libxenon loads its 12-dword shader as 15, with three zeros after it.
	SHADER_PADDING_DWORDS = 3,
	// Xenia sizes a resolve's destination by its tiled layout (xenia:src/xenia/gpu/draw_util.cc:1055-1062).
	TILE_ROWS = 32,
};

// Generated by tools/gen_resolve_vs.py.
static const uint32_t resolve_vertex_shader[] = {
	0x10011002,
	0x00001200,
	0xC4000000,
	0x00000000,
	0x1003C200,
	0x22000000,
	0x00080000,
	0x00253B48,
	0x00000002,
	0xC80F803E,
	0x00000000,
	0xC2000000,
};

static uint32_t depth_clear = DEPTH_CLEAR_FAR;
static uint32_t clears = COPY_CONTROL_COLOR_CLEAR | COPY_CONTROL_DEPTH_CLEAR;

// RB_COLOR_CLEAR wants the packed colour, red low (xenia:src/xenia/gpu/shaders/pixel_formats.xesli:113-116).
static uint32_t packed_8888(uint32_t argb)
{
	return (argb & 0xFF00FF00) | (argb >> 16 & 0xFF) | (argb & 0xFF) << 16;
}

static void put_shader(GpuPackets *packets)
{
	const uint32_t dword_count = sizeof resolve_vertex_shader / 4 + SHADER_PADDING_DWORDS;
	gpu_put_type3(packets, PM4_IM_LOAD_IMMEDIATE, 2 + dword_count);
	gpu_put(packets, SHADER_TYPE_VERTEX);
	gpu_put(packets, dword_count);
	for (uint32_t i = 0; i < dword_count; i++)
		gpu_put(packets, i < sizeof resolve_vertex_shader / 4 ? resolve_vertex_shader[i] : 0);
}

// After a clear, a draw's first block may test the buffer's old values until one draw tests it all (docs/HARDWARE.md).
static void put_hiz_test(GpuPackets *packets, uint32_t hiz_clear)
{
	// Rejected whole it costs less: at z 0 testing greater-than over a clear above 0, at the rectangle's z of 1 over 0.
	const uint32_t z_zero[] = { 0, 0 };
	const bool at_zero = hiz_clear != 0;
	// In eDRAM's no-operation mode this hung the GPU (docs/HARDWARE.md).
	gpu_put_register(packets, RB_MODECONTROL, EDRAM_MODE_DEPTH_ONLY);
	gpu_put_register(packets, RB_DEPTHCONTROL, DEPTH_TEST_NEVER);
	gpu_put_register(packets, RB_HIZCONTROL, HIZ_ENABLE | (at_zero ? HIZ_GREATER : 0));
	if (at_zero) {
		gpu_put_register(packets, PA_CL_VTE_CNTL, VTE_XY_Z_ALREADY_TRANSFORMED | VTE_Z_SCALE_OFFSET);
		gpu_put_registers(packets, PA_CL_VPORT_ZSCALE, z_zero, 2);
	}
	gpu_put_type3(packets, PM4_DRAW_INDX_2, 1);
	gpu_put(packets, RECTANGLE_LIST_AUTO_INDEX_3);
	gpu_put_register(packets, WAIT_UNTIL, WAIT_3D_IDLE_CLEAN);
}

// Xe_ResolveInto, less its scratch write, with the layout Xe_SetRenderTarget gives the target (xe.c:998-1165).
static void resolve(uint32_t source, uint32_t address, uint32_t width, uint32_t height, uint32_t pitch,
	uint32_t dest_info, uint32_t dest_bytes, uint32_t clear_argb)
{
	assert(width % 32 == 0);
	const uint32_t vertices = xsdk_gpu_rectangle(width, height);
	const uint32_t viewport[] = { 0x44000000, 0x44000000, 0xC3B40000, 0x43B40000, 0x3F800000, 0 };
	// A depth resolve can't clear colour (xenia:src/xenia/gpu/xenos.h:925-931).
	const uint32_t copy_clears = source == COPY_SOURCE_DEPTH ? clears & COPY_CONTROL_DEPTH_CLEAR : clears;
	const uint32_t copy[] = { COPY_CONTROL_CONVERT | xsdk_gpu_copy_sample_select() << COPY_SAMPLE_SELECT_SHIFT |
			copy_clears | source,
		address, pitch | height << 16, dest_info };
	const uint32_t program[] = { PROGRAM_CNTL_RESOLVE, 0 };
	const uint32_t indices[] = { 0xFFFF, 0, 0 };
	const uint32_t clip[] = { CLIP_DISABLE, VTX_WINDOW_OFFSET_ENABLE, VTE_XY_Z_ALREADY_TRANSFORMED };
	const uint32_t fetch[] = { vertices | VERTEX_FETCH_TYPE, VERTEX_FETCH_SIZE_6_8IN32, 0, 0, 0, 0 };
	const uint32_t flush_fetch[] = { 0, 0, 0 };
	const uint32_t depth_clears[] = { depth_clear >> HIZ_CLEAR_SHIFT, depth_clear };
	const bool clears_depth = copy_clears & COPY_CONTROL_DEPTH_CLEAR;
	uint32_t dwords[RESOLVE_MAX_DWORDS];
	GpuPackets packets = { .dwords = dwords, .count = 0, .capacity = RESOLVE_MAX_DWORDS };
	xsdk_gpu_put_window(&packets, width, height);
	xsdk_gpu_put_coherency(&packets, COHER_VERTEX_CACHE, vertices, RECTANGLE_INVALIDATE_BYTES);
	xsdk_gpu_put_surface(&packets, width, height);
	gpu_put_register(&packets, RB_COLOR_MASK, 0xF);
	gpu_put_registers(&packets, PA_CL_VPORT_XSCALE, viewport, 6);
	gpu_put_registers(&packets, RB_COPY_CONTROL, copy, 4);
	gpu_put_registers(&packets, RB_HIZ_CLEAR, depth_clears, 2);
	gpu_put_register(&packets, RB_COLOR_CLEAR, packed_8888(clear_argb));
	gpu_put_register(&packets, RB_COLOR_CLEAR_LO, packed_8888(clear_argb));
	gpu_put_register(&packets, RB_MODECONTROL, EDRAM_MODE_COPY);
	gpu_put_register(&packets, RB_MODECONTROL, EDRAM_MODE_COPY);
	gpu_put_register(&packets, RB_DEPTHCONTROL, DEPTH_STENCIL_ALWAYS_WRITE);
	gpu_put_register(&packets, WAIT_UNTIL, WAIT_3D_IDLE_CLEAN);
	gpu_put_type3(&packets, PM4_INVALIDATE_STATE, 1);
	gpu_put(&packets, INVALIDATE_VERTEX_SHADER);
	put_shader(&packets);
	gpu_put_registers(&packets, SQ_PROGRAM_CNTL, program, 2);
	xsdk_gpu_forget_shaders();
	// Writing the buffer clears it to RB_HIZ_CLEAR with depth; testing it would reject the copy (docs/HARDWARE.md).
	gpu_put_register(&packets, RB_HIZCONTROL, clears_depth ? HIZ_WRITE_ENABLE : 0);
	gpu_put_registers(&packets, VGT_MAX_VTX_INDX, indices, 3);
	gpu_put_registers(&packets, PA_CL_CLIP_CNTL, clip, 3);
	gpu_put_register(&packets, COHER_DEST_BASE_7, 0);
	gpu_put_registers(&packets, SHADER_CONSTANT_FETCH_00_0, fetch, 6);
	gpu_put_registers(&packets, SHADER_CONSTANT_FLUSH_FETCH_0, flush_fetch, 3);
	gpu_put_type3(&packets, PM4_DRAW_INDX_2, 1);
	gpu_put(&packets, RECTANGLE_LIST_AUTO_INDEX_3);
	gpu_put_type3(&packets, PM4_EVENT_WRITE, 1);
	gpu_put(&packets, CACHE_FLUSH);
	gpu_put_register(&packets, COHER_DEST_BASE_1, 0);
	xsdk_gpu_put_coherency(&packets, COHER_RESOLVE_ACTIONS, address, dest_bytes);
	gpu_put_register(&packets, RB_COPY_CONTROL, 0);
	gpu_put_register(&packets, RB_COPY_DEST_INFO, 0);
	// Xe_Sync's wait for idle (xe.c:1223-1226, 1278-1282).
	gpu_put_register(&packets, WAIT_UNTIL, WAIT_3D_IDLE_CLEAN);
	if (clears_depth)
		put_hiz_test(&packets, depth_clears[0]);
	xsdk_gpu_write(&packets);
	xsdk_gpu_undo_target();
	if (clears_depth)
		xsdk_gpu_hiz_cleared(width, height, depth_clear);
}

uint32_t xsdk_gpu_resolve_bytes(uint32_t width, uint32_t height)
{
	return width * ((height + TILE_ROWS - 1) & ~(TILE_ROWS - 1)) * 4;
}

void xsdk_gpu_set_depth_clear(float depth, uint8_t stencil)
{
	assert(depth >= 0.0f && depth <= 1.0f);
	// In double: in float, 1.0 * 0xFFFFFF + 0.5 rounds up to 0x1000000, and the shift loses it to 0.
	depth_clear = (uint32_t)(depth * (double)DEPTH_24_MAX + 0.5) << DEPTH_CLEAR_SHIFT | stencil;
}

void xsdk_gpu_resolve(uint32_t address, uint32_t width, uint32_t height, uint32_t clear_argb)
{
	resolve(COPY_SOURCE_COLOR_0, address, width, height, width, COPY_DEST_INFO_8888_SWAP,
		xsdk_gpu_resolve_bytes(width, height), clear_argb);
}

void xsdk_gpu_set_resolve_clears(bool color, bool depth_stencil)
{
	clears = (color ? COPY_CONTROL_COLOR_CLEAR : 0) | (depth_stencil ? COPY_CONTROL_DEPTH_CLEAR : 0);
}

// eDRAM packs red low, so the byte-order formats copy as they are, or with red and blue swapped.
static uint32_t texture_dest_info(uint32_t format)
{
	switch (format) {
	case XSDK_FORMAT_A8R8G8B8:
		return COPY_DEST_INFO_8888_SWAP | COPY_DEST_ENDIAN_8IN32;
	case XSDK_FORMAT_B8G8R8A8:
		return COPY_DEST_INFO_8888_SWAP;
	default:
		assert(format == XSDK_FORMAT_R8G8B8A8);
		return COPY_DEST_INFO_8888;
	}
}

void xsdk_gpu_resolve_texture(const XsdkTexture *texture, uint32_t clear_argb)
{
	// Xenia lays out a resolve's destination only as tiled (xenia:src/xenia/gpu/draw_util.cc:1035-1061).
	assert(texture->tiled);
	// A resolve writes from the corner, so the base can't sit inside the packed tail.
	assert(xsdk_texture_packed_level(texture->width, texture->height) > 0);
	// The pitch is whole tiles of 32 texels, as a resolve's width must be.
	resolve(COPY_SOURCE_COLOR_0, texture->address, texture->pitch, texture->height, texture->pitch,
		texture_dest_info(texture->format), texture->size_bytes, clear_argb);
}

// Direct3D 9 copies depth as k_8_8_8_8 (xenia:src/xenia/gpu/draw_util.cc:968-972): the eDRAM sample's word, depth
// above stencil, swapped into the CPU's order as XSDK_FORMAT_D24S8 reads it.
void xsdk_gpu_resolve_depth_texture(const XsdkTexture *texture)
{
	assert(texture->tiled && texture->format == XSDK_FORMAT_D24S8);
	assert(xsdk_texture_packed_level(texture->width, texture->height) > 0);
	resolve(COPY_SOURCE_DEPTH, texture->address, texture->pitch, texture->height, texture->pitch,
		COPY_DEST_INFO_8888 | COPY_DEST_ENDIAN_8IN32, texture->size_bytes, 0);
}
