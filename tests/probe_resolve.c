// Display registers by index; libxenon's names, and Xenia's style for the pair it doesn't name
// (libxenon:xenos.h:11-54).
enum {
	UNKNOWN_0A10 = 0x0A10,
	UNKNOWN_0A11 = 0x0A11,
	D1CRTC_DOUBLE_BUFFER_CONTROL = 0x183B,
	D1GRPH_PRIMARY_SURFACE_ADDRESS = 0x1844,
	D1GRPH_PITCH = 0x1848,
	D1GRPH_X_END = 0x184D,
	D1GRPH_Y_END = 0x184E,
	DC_LUT_RW_MODE = 0x1921,
	DC_LUT_RW_INDEX = 0x1922,
	DC_LUT_WRITE_EN_MASK = 0x1927,
	DC_LUT_AUTOFILL = 0x1928,
	DC_LUTA_CONTROL = 0x1930,
};

// Type-3 opcodes and the cache flush event (xenia:src/xenia/gpu/xenos.h:1548, 1572-1622).
enum {
	PM4_DRAW_INDX_2 = 0x36,
	PM4_IM_LOAD_IMMEDIATE = 0x2B,
	PM4_INVALIDATE_STATE = 0x3B,
	PM4_WAIT_REG_MEM = 0x3C,
	PM4_EVENT_WRITE = 0x46,
	CACHE_FLUSH = 6,
};

// libxenon's resolve values, decoded with Xenia's registers.h (libxenon:drivers/xenos/xe.c:1069-1165).
enum {
	SURFACE_INFO_640 = 640 | 640 << 18,
	COLOR_INFO_BASE_240 = 240,
	COPY_CONVERT_CLEAR_COLOR = 1 << 20 | 1 << 8,
	COPY_DEST_INFO_8888_SWAP = 1 << 24 | 6 << 7,
	EDRAM_MODE_COPY = 6,
	// What libxenon's set-up leaves for drawing (libxenon:drivers/xenos/xe.c:398-441).
	EDRAM_MODE_COLOR_DEPTH = 4,
	WAIT_3D_IDLE_CLEAN = 1 << 17,
	INVALIDATE_VERTEX_SHADER = 1 << 8,
	PROGRAM_CNTL_RESOLVE = 2 | 1 << 16,
	CLIP_DISABLE = 1 << 16,
	VTX_WINDOW_OFFSET_ENABLE = 1 << 16,
	VTE_XY_Z_ALREADY_TRANSFORMED = 0x300,
	PIX_CENTER_D3D = 4,
	SCREEN_SCISSOR_8192 = 8192 | 8192 << 16,
	VERTEX_FETCH_TYPE = 3,
	VERTEX_FETCH_SIZE_6_8IN32 = 1 << 28 | 6 << 2 | 2,
	RECTANGLE_LIST_AUTO_INDEX_3 = 8 | 2 << 6 | 3 << 16,
	COHER_RESOLVE_ACTIONS = 0x03000100,
	WAIT_REG_MEM_EQUAL = 3,
	COHER_BUSY = 0x80000000,
	WAIT_REG_MEM_INTERVAL = 8,
};

typedef struct {
	const char *name;
	uint32_t clear;
} Resolve;

// Each resolve copies eDRAM out, then clears it to its RB_COLOR_CLEAR value; each colour twice, so the second copies
// it.
static const Resolve resolves[] = {
	{ "white", 0xFFFFFFFF },
	{ "white again", 0xFFFFFFFF },
	{ "green", 0xFF00FF00 },
	{ "green again", 0xFF00FF00 },
};

// Generated by tools/gen_resolve_vs.py.
static const uint32_t resolve_vertex_shader[] = {
	0x10011002,
	0x00001200,
	0xC4000000,
	0x00000000,
	0x1003C200,
	0x22000000,
	0x00080000,
	0x00253B48,
	0x00000002,
	0xC80F803E,
	0x00000000,
	0xC2000000,
};

typedef struct {
	uint32_t dwords[MAX_STAGE_DWORDS];
	uint32_t count;
} Stage;

// GPU registers as titles see them (xenia:src/xenia/gpu/graphics_system.cc:92-95).
static volatile uint32_t *const gpu_registers = (volatile uint32_t *)0x7FC80000;

static void put(Stage *stage, uint32_t value)
{
	stage->dwords[stage->count++] = value;
}

static void put_registers(Stage *stage, uint32_t index, const uint32_t *values, uint32_t count)
{
	put(stage, (count - 1) << 16 | index);
	for (uint32_t i = 0; i < count; i++)
		put(stage, values[i]);
}

static void put_register(Stage *stage, uint32_t index, uint32_t value)
{
	put_registers(stage, index, &value, 1);
}

static void put_type3(Stage *stage, uint32_t opcode, uint32_t payload_dwords)
{
	put(stage, xsdk_gpu_type3(opcode, payload_dwords));
}

static uint32_t float_bits(float value)
{
	uint32_t bits;
	memcpy(&bits, &value, sizeof bits);
	return bits;
}

// Submits the stage and returns whether its fence landed.
static bool submit(const Stage *stage, const char *resolve_name, const char *stage_name)
{
	volatile uint32_t *const ring = xsdk_gpu_reserve(stage->count);
	for (uint32_t i = 0; i < stage->count; i++)
		ring[i] = stage->dwords[i];
	const NTSTATUS status = xsdk_gpu_wait(xsdk_gpu_fence(), FENCE_TIMEOUT_MS);
	xsdk_log_write("resolve: %s: %s: fence 0x%08X", resolve_name, stage_name, (unsigned)status);
	return NT_SUCCESS(status);
}

static void put_state(
	Stage *stage, uint32_t clear, uint32_t destination, uint32_t vertices, uint32_t width, uint32_t height)
{
	const uint32_t window[] = { 0, 0, width | height << 16 };
	const uint32_t screen[] = { 0, SCREEN_SCISSOR_8192 };
	const uint32_t surface[] = { SURFACE_INFO_640, COLOR_INFO_BASE_240, 0 };
	const uint32_t copy[] = { COPY_CONVERT_CLEAR_COLOR, destination, width | height << 16, COPY_DEST_INFO_8888_SWAP };
	const uint32_t clears[] = { clear, clear };
	const uint32_t program[] = { PROGRAM_CNTL_RESOLVE, 0 };
	const uint32_t indices[] = { 0xFFFF, 0, 0 };
	const uint32_t clip[] = { CLIP_DISABLE, VTX_WINDOW_OFFSET_ENABLE, VTE_XY_Z_ALREADY_TRANSFORMED };
	const uint32_t fetch[] = { vertices | VERTEX_FETCH_TYPE, VERTEX_FETCH_SIZE_6_8IN32 };
	put_registers(stage, PA_SC_WINDOW_OFFSET, window, 3);
	put_registers(stage, PA_SC_SCREEN_SCISSOR_TL, screen, 2);
	put_registers(stage, RB_SURFACE_INFO, surface, 3);
	put_register(stage, RB_COLOR_MASK, 0xF);
	put_registers(stage, RB_COPY_CONTROL, copy, 4);
	put_registers(stage, RB_COLOR_CLEAR, clears, 2);
	put_register(stage, RB_MODECONTROL, EDRAM_MODE_COPY);
	put_register(stage, RB_DEPTHCONTROL, 0);
	put_register(stage, WAIT_UNTIL, WAIT_3D_IDLE_CLEAN);
	put_type3(stage, PM4_INVALIDATE_STATE, 1);
	put(stage, INVALIDATE_VERTEX_SHADER);
	// IM_LOAD_IMMEDIATE: shader type 0 is vertex, then start 0 and the size (xenia:command_processor.cc:1565-1576).
	put_type3(stage, PM4_IM_LOAD_IMMEDIATE, 2 + sizeof resolve_vertex_shader / 4);
	put(stage, 0);
	put(stage, sizeof resolve_vertex_shader / 4);
	for (uint32_t i = 0; i < sizeof resolve_vertex_shader / 4; i++)
		put(stage, resolve_vertex_shader[i]);
	put_registers(stage, SQ_PROGRAM_CNTL, program, 2);
	put_register(stage, RB_HIZCONTROL, 0);
	put_registers(stage, VGT_MAX_VTX_INDX, indices, 3);
	put_registers(stage, PA_CL_CLIP_CNTL, clip, 3);
	put_register(stage, PA_SU_VTX_CNTL, PIX_CENTER_D3D);
	put_register(stage, PA_SC_AA_MASK, 0xFFFF);
	put_registers(stage, SHADER_CONSTANT_FETCH_00_0, fetch, 2);
}

// A cache flush, then the coherency wait for the front buffer, in two fenced stages.
static bool flush(const char *name, uint32_t destination, uint32_t width, uint32_t height)
{
	Stage stage = { .count = 0 };
	put_type3(&stage, PM4_EVENT_WRITE, 1);
	put(&stage, CACHE_FLUSH);
	put_register(&stage, COHER_DEST_BASE_1, 0);
	if (!submit(&stage, name, "cache flush"))
		return false;

	stage.count = 0;
	const uint32_t coherency[] = { width * height * 4, destination };
	put_register(&stage, COHER_STATUS_HOST, COHER_RESOLVE_ACTIONS);
	put_registers(&stage, COHER_SIZE_HOST, coherency, 2);
	put_type3(&stage, PM4_WAIT_REG_MEM, 5);
	put(&stage, WAIT_REG_MEM_EQUAL);
	put(&stage, COHER_STATUS_HOST);
	put(&stage, 0);
	put(&stage, COHER_BUSY);
	put(&stage, WAIT_REG_MEM_INTERVAL);
	put_register(&stage, RB_COPY_CONTROL, 0);
	put_register(&stage, RB_COPY_DEST_INFO, 0);
	return submit(&stage, name, "coherency wait");
}

// Returns whether all four stages' fences landed.
static bool resolve_once(
	const Resolve *resolve, uint32_t destination, uint32_t vertices, uint32_t width, uint32_t height)
{
	Stage stage = { .count = 0 };
	put_state(&stage, resolve->clear, destination, vertices, width, height);
	if (!submit(&stage, resolve->name, "state and shader"))
		return false;

	stage.count = 0;
	put_type3(&stage, PM4_DRAW_INDX_2, 1);
	put(&stage, RECTANGLE_LIST_AUTO_INDEX_3);
	if (!submit(&stage, resolve->name, "draw"))
		return false;

	return flush(resolve->name, destination, width, height);
}

// Sets 0x60EC after the surface registers, as XAM does, and waits for the display to clear it (docs/HARDWARE.md).
static void set_surface(uint32_t physical_address, uint32_t pitch)
{
	gpu_registers[UNKNOWN_0A10] = physical_address;
	gpu_registers[UNKNOWN_0A11] = pitch;
	gpu_registers[D1GRPH_PRIMARY_SURFACE_ADDRESS] = physical_address;
	gpu_registers[D1GRPH_PITCH] = pitch;
	gpu_registers[D1GRPH_X_END] = pitch;
	gpu_registers[D1CRTC_DOUBLE_BUFFER_CONTROL] = 1;
	for (uint32_t waited_ms = 0; gpu_registers[D1CRTC_DOUBLE_BUFFER_CONTROL] && waited_ms < APPLY_TIMEOUT_MS;
		waited_ms++)
		(void)xsdk_thread_sleep(1);
	gpu_registers[D1CRTC_DOUBLE_BUFFER_CONTROL] = 0;
}

// libxenon's LUT autofill; a title's display stays black without it (libxenon:drivers/xenos/xenos.c:419-424).
static void fill_lut(void)
{
	gpu_registers[DC_LUTA_CONTROL] = 0;
	gpu_registers[DC_LUT_RW_INDEX] = 0;
	gpu_registers[DC_LUT_RW_MODE] = 0;
	gpu_registers[DC_LUT_WRITE_EN_MASK] = 7;
	gpu_registers[DC_LUT_AUTOFILL] = 1;
	for (uint32_t waited_ms = 0; !(gpu_registers[DC_LUT_AUTOFILL] & 2) && waited_ms < AUTOFILL_TIMEOUT_MS; waited_ms++)
		(void)xsdk_thread_sleep(1);
}

static volatile uint32_t *allocate(uint32_t bytes, uint32_t protect)
{
	const uint32_t rounded = (bytes + PAGE_BYTES - 1) & ~(PAGE_BYTES - 1);
	return MmAllocatePhysicalMemoryEx(
		0, rounded, PAGE_READWRITE | protect | MEM_LARGE_PAGES, 0, UINT32_MAX, PAGE_BYTES);
}

static char classify(uint32_t pixel)
{
	switch (pixel) {
	case MAGENTA:
		return 'M';
	case WHITE:
		return 'W';
	case RED:
		return 'R';
	case GREEN:
		return 'G';
	case BLUE:
		return 'B';
	case 0:
		return '0';
	default:
		return '?';
	}
}

// One character a 4 KB tile, 20 to a row: the tile's first pixel's colour, or '*' if the tile isn't all one value.
static void log_map(const char *when, volatile const uint32_t *pixels, uint32_t pixel_count)
{
	const uint32_t tile_pixels = TILE_BYTES / 4;
	const uint32_t tiles_per_row = 640 / TILE_PIXELS;
	char row[640 / TILE_PIXELS + 1];
	uint32_t other_values[MAX_OTHER_VALUES];
	uint32_t other_count = 0;
	xsdk_log_write("resolve: %s:", when);
	for (uint32_t tile = 0; tile < pixel_count / tile_pixels; tile++) {
		volatile const uint32_t *const first = &pixels[tile * tile_pixels];
		char mark = classify(first[0]);
		for (uint32_t i = 1; i < tile_pixels; i++) {
			if (first[i] != first[0]) {
				mark = '*';
				break;
			}
		}
		if (classify(first[0]) == '?' && other_count < MAX_OTHER_VALUES)
			other_values[other_count++] = first[0];
		row[tile % tiles_per_row] = mark;
		if (tile % tiles_per_row == tiles_per_row - 1) {
			row[tiles_per_row] = '\0';
			xsdk_log_write("resolve:   %s", row);
		}
	}
	for (uint32_t i = 0; i < other_count; i++)
		xsdk_log_write("resolve:   other value %08X", (unsigned)other_values[i]);
}

static void hold(const char *what)
{
	xsdk_log_write("resolve: showing %s for %u ms", what, (unsigned)HOLD_MS);
	(void)xsdk_thread_sleep(HOLD_MS);
}

int main(void)
{
	xsdk_log_write("resolve probe");
	const uint32_t old_surface = gpu_registers[D1GRPH_PRIMARY_SURFACE_ADDRESS];
	// Xenia has no display registers; there the probe still resolves, and the read-back pixels show the result.
	const bool has_display = gpu_registers[D1GRPH_PITCH] != 0;
	const uint32_t width = has_display ? gpu_registers[D1GRPH_PITCH] : 640;
	const uint32_t height = has_display ? gpu_registers[D1GRPH_Y_END] : 480;
	const uint32_t pixel_count = width * ((height + TILE_PIXELS - 1) & ~(TILE_PIXELS - 1));
	volatile uint32_t *const pixels = allocate(pixel_count * 4, PAGE_WRITECOMBINE);
	volatile uint32_t *const vertices = allocate(PAGE_BYTES, PAGE_NOCACHE);
	if (width != 640 || height != 480 || !pixels || !vertices) {
		xsdk_log_write("resolve: no buffers for a %ux%u mode", (unsigned)width, (unsigned)height);
		return 1;
	}
	for (uint32_t i = 0; i < pixel_count; i++)
		pixels[i] = MAGENTA;
	// libxenon's rectangle: three corners, half a pixel up and left (libxenon:drivers/xenos/xe.c:1074-1081).
	const float corners[6] = { -0.5f, -0.5f, width - 0.5f, 0, width - 0.5f, height - 0.5f };
	for (uint32_t i = 0; i < 6; i++)
		vertices[i] = float_bits(corners[i]);
	__asm__ volatile("sync" ::: "memory");
	const uint32_t pixels_physical = MmGetPhysicalAddress((const void *)pixels);
	const uint32_t vertices_physical = MmGetPhysicalAddress((const void *)vertices);
	xsdk_log_write("resolve: front buffer at physical %08X, vertices at %08X", (unsigned)pixels_physical,
		(unsigned)vertices_physical);

	const NTSTATUS status = xsdk_gpu_open();
	if (!NT_SUCCESS(status)) {
		xsdk_log_write("resolve: xsdk_gpu_open returned 0x%08X", (unsigned)status);
		return 1;
	}
	if (has_display) {
		fill_lut();
		set_surface(pixels_physical, width);
	}
	hold("magenta from the CPU");

	for (uint32_t i = 0; i < sizeof resolves / sizeof resolves[0]; i++) {
		// Magenta first, so each map shows what this resolve wrote.
		for (uint32_t p = 0; p < pixel_count; p++)
			pixels[p] = MAGENTA;
		__asm__ volatile("sync" ::: "memory");
		bool finished = resolve_once(&resolves[i], pixels_physical, vertices_physical, width, height);
		log_map(resolves[i].name, pixels, pixel_count);
		finished = finished && flush("flushing again", pixels_physical, width, height);
		log_map("after flushing again", pixels, pixel_count);
		if (!finished) {
			xsdk_log_write("resolve: a stage didn't finish; stopping");
			break;
		}
		xsdk_log_write("resolve: holding for %u ms", (unsigned)HOLD_MS_SHORT);
		(void)xsdk_thread_sleep(HOLD_MS_SHORT);
	}

	// XAM's device draws after the title exits, so copy mode mustn't outlive the probe (docs/HARDWARE.md).
	Stage stage = { .count = 0 };
	put_register(&stage, RB_MODECONTROL, EDRAM_MODE_COLOR_DEPTH);
	(void)submit(&stage, "exit", "drawing mode back");
	if (has_display)
		set_surface(old_surface, width);
	return 0;
}
