// Sets the GPU up and resolves into the displayed front buffer as libxenon does, mapping what each resolve wrote.

enum {
	PAGE_BYTES = 0x10000,
	HOLD_MS = 3000,
	FENCE_TIMEOUT_MS = 1000,
	APPLY_TIMEOUT_MS = 100,
	AUTOFILL_TIMEOUT_MS = 100,
	TILE_PIXELS = 32,
	HOLD_MS_SHORT = 2000,
	TILE_BYTES = 4096,
	TILES_PER_ROW = 640 / TILE_PIXELS,
	MAX_TILES = 640 * 480 * 4 / TILE_BYTES,
	MAX_COUNTED_VALUES = 6,
	REGISTERS_PER_LINE = 6,
	SCREEN_SCISSOR_8192 = 8192 | 8192 << 16,
	// The display's colours as words in memory, bytes B, G, R, A (docs/HARDWARE.md).
	MAGENTA = 0xFF00FFFF,
	WHITE = 0xFFFFFFFF,
	RED = 0x0000FFFF,
	GREEN = 0x00FF00FF,
	BLUE = 0xFF0000FF,
};

typedef struct {
	const char *name;
	uint32_t clear;
} Resolve;

// Each resolve copies eDRAM out, then clears it to its colour; each colour twice, so the second copies it.
static const Resolve resolves[] = {
	{ "white 1", 0xFFFFFFFF },
	{ "white 2", 0xFFFFFFFF },
	{ "green 1", 0xFF00FF00 },
	{ "green 2", 0xFF00FF00 },
	{ "blue 1", 0xFF0000FF },
	{ "blue 2", 0xFF0000FF },
	{ "white 3", 0xFFFFFFFF },
	{ "white 4", 0xFFFFFFFF },
};

typedef struct {
	const char *name;
	void (*put)(ProbeStage *stage);
} SetUpStage;

// Xe_pGInit's parts in order, each fenced, so the log shows any that wedges the GPU.
