// libxenon writes these too; only logged until it's known what they control (libxenon:drivers/xenos/xe.c:476-477).
static const uint32_t logged_registers[] = { UNKNOWN_0A02, UNKNOWN_0A03, UNKNOWN_0A04, UNKNOWN_0A05 };

typedef struct {
	uint32_t values[MAX_COUNTED_VALUES];
	uint32_t pixels[MAX_COUNTED_VALUES];
	uint32_t value_count;
	uint32_t uncounted_pixels;
} Census;

// Generated by tools/gen_resolve_vs.py.
static const uint32_t resolve_vertex_shader[] = {
	0x10011002,
	0x00001200,
	0xC4000000,
	0x00000000,
	0x1003C200,
	0x22000000,
	0x00080000,
	0x00253B48,
	0x00000002,
	0xC80F803E,
	0x00000000,
	0xC2000000,
};

static uint32_t saved_values[sizeof saved_registers / sizeof saved_registers[0]];
static ProbeStage stage;

static uint32_t float_bits(float value)
{
	uint32_t bits;
	memcpy(&bits, &value, sizeof bits);
	return bits;
}

// Submits the stage, empties it, and returns whether its fence landed.
static bool submit(const char *name, const char *what)
{
	volatile uint32_t *const ring = xsdk_gpu_reserve(stage.count);
	for (uint32_t i = 0; i < stage.count; i++)
		ring[i] = stage.dwords[i];
	const uint32_t dword_count = stage.count;
	stage.count = 0;
	const NTSTATUS status = xsdk_gpu_wait(xsdk_gpu_fence(), FENCE_TIMEOUT_MS);
	xsdk_log_write("resolve: %s: %s, %u dwords: fence 0x%08X", name, what, (unsigned)dword_count, (unsigned)status);
	return NT_SUCCESS(status);
}

// Index and value, six to a line.
static void log_registers(const char *when, const uint32_t *indices, uint32_t count)
{
	for (uint32_t first = 0; first < count; first += REGISTERS_PER_LINE) {
		char line[REGISTERS_PER_LINE * 14 + 1];
		uint32_t length = 0;
		for (uint32_t i = first; i < count && i < first + REGISTERS_PER_LINE; i++)
			length += (uint32_t)snprintf(&line[length], sizeof line - length, " %04X %08X", (unsigned)indices[i],
				(unsigned)probe_gpu_registers[indices[i]]);
		xsdk_log_write("resolve: %s:%s", when, line);
	}
}

static void save_registers(void)
{
	for (uint32_t i = 0; i < sizeof saved_registers / sizeof saved_registers[0]; i++)
		saved_values[i] = probe_gpu_registers[saved_registers[i]];
}

// XAM's device draws after the title exits, so it gets back what it had (docs/HARDWARE.md).
static void restore_registers(void)
{
	probe_put_register(&stage, WAIT_UNTIL, WAIT_3D_IDLE_CLEAN);
	for (uint32_t i = 0; i < sizeof saved_registers / sizeof saved_registers[0]; i++)
		probe_put_register(&stage, saved_registers[i], saved_values[i]);
	(void)submit("exit", "registers back");
}

// Returns whether every stage's fence landed.
static bool set_up_like_libxenon(void)
{
	for (uint32_t i = 0; i < sizeof set_up_stages / sizeof set_up_stages[0]; i++) {
		set_up_stages[i].put(&stage);
		if (!submit("set-up", set_up_stages[i].name))
			return false;
	}
	// Xe_Init invalidates the vertex cache over all memory last (libxenon:drivers/xenos/xe.c:992).
	put_libxenon_coherency(&stage, COHER_VERTEX_CACHE, 0, ALL_MEMORY_BYTES);
	if (!submit("set-up", "vertex cache"))
		return false;
	// libxenon leaves this at its reset value; D3D keeps it whole (xenia:src/xenia/gpu/draw_util.cc:575-576).
	const uint32_t screen[] = { 0, SCREEN_SCISSOR_8192 };
	probe_put_registers(&stage, PA_SC_SCREEN_SCISSOR_TL, screen, 2);
	return submit("set-up", "screen scissor");
}

static bool resolve_once(const Resolve *resolve, uint32_t destination, uint32_t vertices)
{
	put_libxenon_resolve(
		&stage, resolve->clear, destination, vertices, resolve_vertex_shader, sizeof resolve_vertex_shader / 4);
	return submit(resolve->name, "resolve");
}

// Sets 0x60EC after the surface registers, as XAM does, and waits for the display to clear it (docs/HARDWARE.md).
static void set_surface(uint32_t physical_address, uint32_t pitch)
{
	probe_gpu_registers[UNKNOWN_0A10] = physical_address;
	probe_gpu_registers[UNKNOWN_0A11] = pitch;
	probe_gpu_registers[D1GRPH_PRIMARY_SURFACE_ADDRESS] = physical_address;
	probe_gpu_registers[D1GRPH_PITCH] = pitch;
	probe_gpu_registers[D1GRPH_X_END] = pitch;
	probe_gpu_registers[D1CRTC_DOUBLE_BUFFER_CONTROL] = 1;
	for (uint32_t waited_ms = 0; probe_gpu_registers[D1CRTC_DOUBLE_BUFFER_CONTROL] && waited_ms < APPLY_TIMEOUT_MS;
		waited_ms++)
		(void)xsdk_thread_sleep(1);
	probe_gpu_registers[D1CRTC_DOUBLE_BUFFER_CONTROL] = 0;
}

// libxenon's LUT autofill; a title's display stays black without it (libxenon:drivers/xenos/xenos.c:419-424).
static void fill_lut(void)
{
	probe_gpu_registers[DC_LUTA_CONTROL] = 0;
	probe_gpu_registers[DC_LUT_RW_INDEX] = 0;
	probe_gpu_registers[DC_LUT_RW_MODE] = 0;
	probe_gpu_registers[DC_LUT_WRITE_EN_MASK] = 7;
	probe_gpu_registers[DC_LUT_AUTOFILL] = 1;
	for (uint32_t waited_ms = 0; !(probe_gpu_registers[DC_LUT_AUTOFILL] & 2) && waited_ms < AUTOFILL_TIMEOUT_MS;
		waited_ms++)
		(void)xsdk_thread_sleep(1);
}

static volatile uint32_t *allocate(uint32_t bytes, uint32_t protect)
{
	const uint32_t rounded = (bytes + PAGE_BYTES - 1) & ~(PAGE_BYTES - 1);
	return MmAllocatePhysicalMemoryEx(
		0, rounded, PAGE_READWRITE | protect | MEM_LARGE_PAGES, 0, UINT32_MAX, PAGE_BYTES);
}

static char classify(uint32_t pixel)
{
	switch (pixel) {
	case MAGENTA:
		return 'M';
	case WHITE:
		return 'W';
	case RED:
		return 'R';
	case GREEN:
		return 'G';
	case BLUE:
		return 'B';
	case 0:
		return '0';
	default:
		return '?';
	}
}

// The tile's colour, or '*' if it holds more than one value.
static char mark_tile(volatile const uint32_t *tile)
{
	const uint32_t first = tile[0];
	for (uint32_t i = 1; i < TILE_BYTES / 4; i++) {
		if (tile[i] != first)
			return '*';
	}
	return classify(first);
}

// One character a 4 KB tile, 20 to a row, or one line if every tile is alike.
static void log_map(const char *when, volatile const uint32_t *pixels, uint32_t pixel_count)
{
	const uint32_t tile_pixels = TILE_BYTES / 4;
	const uint32_t tile_count = pixel_count / tile_pixels;
	char marks[MAX_TILES];
	bool alike = true;
	for (uint32_t tile = 0; tile < tile_count; tile++) {
		marks[tile] = mark_tile(&pixels[tile * tile_pixels]);
		alike = alike && marks[tile] == marks[0];
	}
	if (alike) {
		xsdk_log_write("resolve: %s: every tile %c", when, marks[0]);
		return;
	}
	xsdk_log_write("resolve: %s:", when);
	for (uint32_t row = 0; row < tile_count; row += TILES_PER_ROW)
		xsdk_log_write("resolve:   %.*s", (int)TILES_PER_ROW, &marks[row]);
}

static void count_pixel(Census *census, uint32_t pixel)
{
	for (uint32_t i = 0; i < census->value_count; i++) {
		if (census->values[i] == pixel) {
			census->pixels[i]++;
			return;
		}
	}
	if (census->value_count == MAX_COUNTED_VALUES) {
		census->uncounted_pixels++;
		return;
	}
	census->values[census->value_count] = pixel;
	census->pixels[census->value_count++] = 1;
}

// How many pixels hold each of the first values seen.
static void log_values(volatile const uint32_t *pixels, uint32_t pixel_count)
{
	Census census = { .value_count = 0 };
	for (uint32_t p = 0; p < pixel_count; p++)
		count_pixel(&census, pixels[p]);
	for (uint32_t i = 0; i < census.value_count; i++)
		xsdk_log_write("resolve:   %08X in %u pixels", (unsigned)census.values[i], (unsigned)census.pixels[i]);
	if (census.uncounted_pixels)
		xsdk_log_write("resolve:   %u pixels hold other values", (unsigned)census.uncounted_pixels);
}

static void hold(const char *what)
{
	xsdk_log_write("resolve: showing %s for %u ms", what, (unsigned)HOLD_MS);
	(void)xsdk_thread_sleep(HOLD_MS);
}

int main(void)
{
	xsdk_log_write("resolve probe");
	const uint32_t old_surface = probe_gpu_registers[D1GRPH_PRIMARY_SURFACE_ADDRESS];
	// Xenia has no display registers; there the probe still resolves, and the read-back pixels show the result.
	const bool has_display = probe_gpu_registers[D1GRPH_PITCH] != 0;
	const uint32_t width = has_display ? probe_gpu_registers[D1GRPH_PITCH] : 640;
	const uint32_t height = has_display ? probe_gpu_registers[D1GRPH_Y_END] : 480;
	const uint32_t pixel_count = width * ((height + TILE_PIXELS - 1) & ~(TILE_PIXELS - 1));
	volatile uint32_t *const pixels = allocate(pixel_count * 4, PAGE_WRITECOMBINE);
	volatile uint32_t *const vertices = allocate(PAGE_BYTES, PAGE_NOCACHE);
	if (width != 640 || height != 480 || !pixels || !vertices) {
		xsdk_log_write("resolve: no buffers for a %ux%u mode", (unsigned)width, (unsigned)height);
		return 1;
	}
	for (uint32_t i = 0; i < pixel_count; i++)
		pixels[i] = MAGENTA;
	// libxenon's rectangle: three corners, half a pixel up and left (libxenon:drivers/xenos/xe.c:1074-1081).
	const float corners[6] = { -0.5f, -0.5f, width - 0.5f, 0, width - 0.5f, height - 0.5f };
	for (uint32_t i = 0; i < 6; i++)
		vertices[i] = float_bits(corners[i]);
	__asm__ volatile("sync" ::: "memory");
	const uint32_t pixels_physical = MmGetPhysicalAddress((const void *)pixels);
	const uint32_t vertices_physical = MmGetPhysicalAddress((const void *)vertices);
	xsdk_log_write("resolve: front buffer at physical %08X, vertices at %08X", (unsigned)pixels_physical,
		(unsigned)vertices_physical);

	const NTSTATUS status = xsdk_gpu_open();
	if (!NT_SUCCESS(status)) {
		xsdk_log_write("resolve: xsdk_gpu_open returned 0x%08X", (unsigned)status);
		return 1;
	}
	save_registers();
	log_registers("after taking the GPU", saved_registers, sizeof saved_registers / sizeof saved_registers[0]);
	log_registers("only logged", logged_registers, sizeof logged_registers / sizeof logged_registers[0]);
	if (has_display) {
		fill_lut();
		set_surface(pixels_physical, width);
	}
	hold("magenta from the CPU");

	const bool ready = set_up_like_libxenon();
	log_registers("after the set-up", saved_registers, sizeof saved_registers / sizeof saved_registers[0]);
	for (uint32_t i = 0; ready && i < sizeof resolves / sizeof resolves[0]; i++) {
		// Magenta first, so each map shows what this resolve wrote.
		for (uint32_t p = 0; p < pixel_count; p++)
			pixels[p] = MAGENTA;
		__asm__ volatile("sync" ::: "memory");
		const bool finished = resolve_once(&resolves[i], pixels_physical, vertices_physical);
		log_map(resolves[i].name, pixels, pixel_count);
		log_values(pixels, pixel_count);
		if (!finished) {
			xsdk_log_write("resolve: a resolve didn't finish; stopping");
			break;
		}
		xsdk_log_write("resolve: holding for %u ms", (unsigned)HOLD_MS_SHORT);
		(void)xsdk_thread_sleep(HOLD_MS_SHORT);
	}

	restore_registers();
	if (has_display)
		set_surface(old_surface, width);
	return 0;
}
