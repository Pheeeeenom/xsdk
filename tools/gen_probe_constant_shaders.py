#!/usr/bin/env python3
"""Generate the shader variants tests/probe_constants.c steps through, each adding one constant feature to the last.

Vertex shaders, packed as in tools/gen_constant_shaders.py: a plain one passing the position on as both position and
colour, and one taking its colour from c2. Pixel shaders, written in xost's assembly and assembled by its text
assembler (xenos-toolchain/xasm/textasm.py), whose conventions tools/gen_constant_shaders.py checks against hand
packing: one adding c0, one adding c1 instead when boolean 128 is set, and one adding c2 once a pass of loop 0. The
probe takes the full pair from tests/constant_shaders.h and the passthrough pixel shader from tests/triangle_shaders.h.
Prints a C header, then the disassembly on stderr.
"""

import struct
import sys

import gen_constant_shaders as cst
import gen_triangle_shaders as tri
from gen_triangle_shaders import ce, container, enc, xu
from xasm import textasm

PIXEL_SHADERS = {
    "probe_constant_pixel_shader": """
      exec
   add r1, r0, c0
      alloc colors
      exece
   max oC0, r1, r1
""",
    "probe_bool_pixel_shader": """
      exec
   add r1, r0, c0
      cexec b128
   add r1, r0, c1
      alloc colors
      exece
   max oC0, r1, r1
""",
    "probe_loop_pixel_shader": """
      exec
   add r1, r0, c0
      loop i0, L1
label L0
      exec
   add r1, r1, c2
      endloop i0, L0
label L1
      alloc colors
      exece
   max oC0, r1, r1
""",
}


def vertex_shader(color_from_constant):
    # exec {fetch position}; alloc position; exec {oPos = position}; alloc interpolators; exece {o0 = position or c2}.
    control_flow = [
        tri.execute(3, 1, sequence=cst.SEQUENCE_ONE_FETCH, vc_hi=cst.VERTEX_CACHE_ONE_FETCH),
        enc.build_cf_alloc(alloc_type=tri.ALLOC_POSITION),
        tri.execute(4, 1),
        enc.build_cf_alloc(alloc_type=tri.ALLOC_INTERPOLATORS),
        tri.execute(5, 1, end=True),
    ]
    if color_from_constant:
        color = enc.build_alu(vector_opcode=xu.AluVectorOpcode.kMax, vector_dest=tri.EXPORT_INTERPOLATOR_0,
            vector_write_mask=tri.WRITE_XYZW, is_export=True, src1_reg=cst.COLOR_CONSTANT, src1_is_temp=False,
            src2_reg=cst.COLOR_CONSTANT, src2_is_temp=False, src3_is_temp=True)
    else:
        color = tri.export(tri.EXPORT_INTERPOLATOR_0, cst.POSITION_REGISTER)
    dwords = tri.pack(control_flow,
        [tri.fetch(cst.POSITION_REGISTER), tri.export(tri.EXPORT_POSITION, cst.POSITION_REGISTER), color])
    return ce.build_container(
        "vertex", struct.pack(f">{len(dwords)}I", *dwords), constants=[],
        program_control=tri.program_control(vs_num_reg=cst.POSITION_REGISTER, vs_resource=1, vs_export_count=0),
        context_misc=0,
        interpolators=[ce.Interpolator(tri.EXPORT_INTERPOLATOR_0, ce.USAGE_COLOR, 0)],
        vertex_elements=[ce.VertexElement(3, tri.USAGE_POSITION, 0)],
        creator=tri.CREATOR)


def pixel_shader(text):
    return ce.build_container(
        "pixel", textasm.assemble_text(text, "pixel"), constants=[],
        program_control=tri.program_control(ps_num_reg=cst.SUM_REGISTER, ps_export_mode=tri.PS_EXPORT_MODE_COLOR),
        context_misc=tri.CONTEXT_MISC_CENTROIDS_AND_CENTERS,
        interpolators=[ce.Interpolator(tri.EXPORT_INTERPOLATOR_0, ce.USAGE_COLOR, 0)],
        ps_field18=tri.PS_INTERPOLATOR_WORD, creator=tri.CREATOR)


def main():
    print("#ifndef XSDK_PROBE_CONSTANT_SHADERS_H\n#define XSDK_PROBE_CONSTANT_SHADERS_H\n\n#include <stdint.h>\n")
    print("// Generated by tools/gen_probe_constant_shaders.py.")
    shaders = [("probe_plain_vertex_shader", vertex_shader(False)),
               ("probe_constant_vertex_shader", vertex_shader(True))]
    shaders += [(name, pixel_shader(text)) for name, text in PIXEL_SHADERS.items()]
    for name, blob in shaders:
        tri.print_array(name, blob)
        parsed = container.Container(blob)
        print(f"{name}:", file=sys.stderr)
        print(xu.disassemble(parsed.ucode_dwords, parsed.shader_type), file=sys.stderr)
    print("\n#endif")


if __name__ == "__main__":
    main()
