#!/usr/bin/env python3
"""Generate one assembly file per kernel or XAM import listed in imports/imports.txt."""

import argparse
import sys
from pathlib import Path

# Kernel calls read arguments 9 and up from 8-byte slots at r1+0x54 (xenia:src/xenia/kernel/util/shim_utils.h:52).
KERNEL_FRAME_HEADER = 0x50
REGISTER_ARGS = 8
LIBRARY_NAME_BYTES = 16

# A record's top byte is its type and its low 16 bits its ordinal (xenia:src/xenia/cpu/xex_module.cc:1133-1134).
RECORD_VARIABLE = 0x00000000
RECORD_THUNK = 0x01000000
# A working XDK-built title's thunks repeat the record in word 1 with type 2 (user's console files).
RECORD_THUNK_SECOND = 0x02000000


def parse_imports(path):
    imports = []
    for line_number, line in enumerate(path.read_text().splitlines(), 1):
        fields = line.split("#", 1)[0].split()
        if not fields:
            continue
        if len(fields) != 4:
            sys.exit(f"{path}:{line_number}: expected library, ordinal, name and argument count")
        library, ordinal, name, args = fields
        if len(library) >= LIBRARY_NAME_BYTES:
            sys.exit(f"{path}:{line_number}: library name {library} is too long")
        variadic = args == "..."
        imports.append({
            "library": library,
            "ordinal": int(ordinal, 16),
            "name": name,
            "args": REGISTER_ARGS if variadic else int(args),
            "variadic": variadic,
        })
    return imports


def frame_size(stack_args):
    return (KERNEL_FRAME_HEADER + 8 * stack_args + 15) & ~15


def stack_arg_copies(stack_args, frame):
    lines = []
    if stack_args:
        lines.append("\tli\tr12, 0")
    for slot in range(stack_args):
        # GCC passes them 4 bytes apart from 8(r1); the kernel reads the low word of each slot.
        lines.append(f"\tlwz\tr11, {frame + 8 + 4 * slot}(r1)")
        lines.append(f"\tstw\tr12, {KERNEL_FRAME_HEADER + 8 * slot}(r1)")
        lines.append(f"\tstw\tr11, {KERNEL_FRAME_HEADER + 8 * slot + 4}(r1)")
    return lines


def library_name_directive(library):
    padding = "\\0" * (LIBRARY_NAME_BYTES - len(library))
    return f'\t.ascii\t"{library}{padding}"'


def generate(entry):
    name = entry["name"]
    ordinal = entry["ordinal"]
    stack_args = max(entry["args"] - REGISTER_ARGS, 0)
    frame = frame_size(stack_args)
    lines = [
        f"// Generated by tools/gen_imports.py from imports/imports.txt: {entry['library']} ordinal {ordinal:#05x}.",
        "",
        f"\t.section .rodata.xsdk_imp_{name}, \"a\"",
        "\t.balign 4",
        f"\t.globl\txsdk_imp_{name}",
        f"xsdk_imp_{name}:",
        f"\t.long\t{RECORD_VARIABLE | ordinal:#010x}",
        "",
        f"\t.section .text.xsdk_thunk_{name}, \"ax\"",
        "\t.balign 16",
        "// The loader rewrites the first two words to load the export's address into r11.",
        f"xsdk_thunk_{name}:",
        f"\t.long\t{RECORD_THUNK | ordinal:#010x}",
        f"\t.long\t{RECORD_THUNK_SECOND | ordinal:#010x}",
        "\tmtctr\tr11",
        "\tbctr",
        "",
        f"\t.section .text.xsdk_stub_{name}, \"ax\"",
        "\t.balign 4",
        f"\t.globl\t{name}",
        f"\t.type\t{name}, @function",
        f"{name}:",
        "\tmflr\tr0",
        "\tstw\tr0, 4(r1)",
        f"\tstwu\tr1, -{frame}(r1)",
        *stack_arg_copies(stack_args, frame),
        f"\tbl\txsdk_thunk_{name}",
        f"\taddi\tr1, r1, {frame}",
        "\tlwz\tr0, 4(r1)",
        "\tmtlr\tr0",
        "\tblr",
        f"\t.size\t{name}, . - {name}",
        "",
        "// elf2xex reads these records to build the import libraries header.",
        "\t.section .xsdk.imports, \"\"",
        f"\t.long\txsdk_imp_{name}",
        f"\t.long\txsdk_thunk_{name}",
        f"\t.long\t{ordinal:#x}",
        "\t.long\t0",
        library_name_directive(entry["library"]),
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--list", action="store_true", help="print the import names instead of generating files")
    parser.add_argument("table", type=Path, help="imports/imports.txt")
    parser.add_argument("output", type=Path, nargs="?", help="directory for the generated .S files")
    args = parser.parse_args()

    imports = parse_imports(args.table)
    if args.list:
        print(" ".join(entry["name"] for entry in imports))
        return
    if args.output is None:
        parser.error("output directory required")
    args.output.mkdir(parents=True, exist_ok=True)
    for entry in imports:
        path = args.output / f"{entry['name']}.S"
        text = generate(entry)
        if not path.exists() or path.read_text() != text:
            path.write_text(text, newline="\n")


if __name__ == "__main__":
    main()
