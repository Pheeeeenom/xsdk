#!/usr/bin/env python3
"""Generate one assembly file per kernel or XAM import listed in imports/imports.txt."""

import argparse
import re
import sys
from pathlib import Path

# The stubs pass r3-r10 through as they are, and the console's MSVC code and xsdk's GCC agree there only on integers
# and pointers of 32 bits or less: 64-bit integers, floating point and structs by value travel differently
# (docs/HARDWARE.md, "Calls between xsdk's GCC and the console's MSVC").
BY_VALUE_TYPES = re.compile(r"\b(u?int64_t|LONGLONG|ULONGLONG|LARGE_INTEGER|double|float|struct|union)\b")
QUALIFIERS = re.compile(r"\b(const|volatile|extern|static|inline)\b")

# Kernel calls read arguments 9 and up from 8-byte slots at r1+0x54 (xenia:src/xenia/kernel/util/shim_utils.h:52).
KERNEL_FRAME_HEADER = 0x50
REGISTER_ARGS = 8
LIBRARY_NAME_BYTES = 16

# A record's top byte is its type and its low 16 bits its ordinal (xenia:src/xenia/cpu/xex_module.cc:1133-1134).
RECORD_VARIABLE = 0x00000000
RECORD_THUNK = 0x01000000
# A working XDK-built title's thunks repeat the record in word 1 with type 2 (user's console files).
RECORD_THUNK_SECOND = 0x02000000


def parse_imports(path):
    imports = []
    for line_number, line in enumerate(path.read_text().splitlines(), 1):
        fields = line.split("#", 1)[0].split()
        if not fields:
            continue
        if len(fields) != 4:
            sys.exit(f"{path}:{line_number}: expected library, ordinal, name and argument count")
        library, ordinal, name, args = fields
        if len(library) >= LIBRARY_NAME_BYTES:
            sys.exit(f"{path}:{line_number}: library name {library} is too long")
        variadic = args == "..."
        variable = args == "variable"
        imports.append({
            "library": library,
            "ordinal": int(ordinal, 16),
            "name": name,
            "args": 0 if variable else REGISTER_ARGS if variadic else int(args),
            "variadic": variadic,
            "variable": variable,
        })
    return imports


def frame_size(stack_args):
    return (KERNEL_FRAME_HEADER + 8 * stack_args + 15) & ~15


def stack_arg_copies(stack_args, frame):
    lines = []
    if stack_args:
        lines.append("\tli\tr12, 0")
    for slot in range(stack_args):
        # GCC passes them 4 bytes apart from 8(r1); the kernel reads the low word of each slot.
        lines.append(f"\tlwz\tr11, {frame + 8 + 4 * slot}(r1)")
        lines.append(f"\tstw\tr12, {KERNEL_FRAME_HEADER + 8 * slot}(r1)")
        lines.append(f"\tstw\tr11, {KERNEL_FRAME_HEADER + 8 * slot + 4}(r1)")
    return lines


def library_name_directive(library):
    padding = "\\0" * (LIBRARY_NAME_BYTES - len(library))
    return f'\t.ascii\t"{library}{padding}"'


def import_record(slot, thunk, entry):
    return [
        "// elf2xex reads these records to build the import libraries header.",
        "\t.section .xsdk.imports, \"\"",
        f"\t.long\t{slot}",
        f"\t.long\t{thunk}",
        f"\t.long\t{entry['ordinal']:#x}",
        "\t.long\t0",
        library_name_directive(entry["library"]),
        "",
    ]


# A variable gets no thunk: the loader writes its address into the record (xenia:src/xenia/cpu/xex_module.cc:1173).
def generate_variable(entry):
    name = entry["name"]
    ordinal = entry["ordinal"]
    lines = [
        f"// Generated by tools/gen_imports.py from imports/imports.txt: {entry['library']} ordinal {ordinal:#05x}.",
        "",
        f"\t.section .rodata.xsdk_imp_{name}, \"a\"",
        "\t.balign 4",
        f"\t.globl\t{name}",
        f"\t.type\t{name}, @object",
        f"{name}:",
        f"\t.long\t{RECORD_VARIABLE | ordinal:#010x}",
        f"\t.size\t{name}, 4",
        "",
        *import_record(name, 0, entry),
    ]
    return "\n".join(lines)


def generate(entry):
    if entry["variable"]:
        return generate_variable(entry)
    name = entry["name"]
    ordinal = entry["ordinal"]
    stack_args = max(entry["args"] - REGISTER_ARGS, 0)
    frame = frame_size(stack_args)
    lines = [
        f"// Generated by tools/gen_imports.py from imports/imports.txt: {entry['library']} ordinal {ordinal:#05x}.",
        "",
        f"\t.section .rodata.xsdk_imp_{name}, \"a\"",
        "\t.balign 4",
        f"\t.globl\txsdk_imp_{name}",
        f"xsdk_imp_{name}:",
        f"\t.long\t{RECORD_VARIABLE | ordinal:#010x}",
        "",
        f"\t.section .text.xsdk_thunk_{name}, \"ax\"",
        "\t.balign 16",
        "// The loader rewrites the first two words to load the export's address into r11.",
        f"xsdk_thunk_{name}:",
        f"\t.long\t{RECORD_THUNK | ordinal:#010x}",
        f"\t.long\t{RECORD_THUNK_SECOND | ordinal:#010x}",
        "\tmtctr\tr11",
        "\tbctr",
        "",
        f"\t.section .text.xsdk_stub_{name}, \"ax\"",
        "\t.balign 4",
        f"\t.globl\t{name}",
        f"\t.type\t{name}, @function",
        f"{name}:",
        "\tmflr\tr0",
        "\tstw\tr0, 4(r1)",
        f"\tstwu\tr1, -{frame}(r1)",
        *stack_arg_copies(stack_args, frame),
        f"\tbl\txsdk_thunk_{name}",
        f"\taddi\tr1, r1, {frame}",
        "\tlwz\tr0, 4(r1)",
        "\tmtlr\tr0",
        "\tblr",
        f"\t.size\t{name}, . - {name}",
        "",
        *import_record(f"xsdk_imp_{name}", f"xsdk_thunk_{name}", entry),
    ]
    return "\n".join(lines)


def declarations_text(root):
    files = sorted((root / "include" / "xsdk").glob("*.h")) + sorted((root / "src").glob("*.[ch]"))
    text = "\n".join(path.read_text() for path in files)
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", " ", text)


def closing(text, start, open_char, close_char):
    depth = 0
    for at in range(start, len(text)):
        depth += {open_char: 1, close_char: -1}.get(text[at], 0)
        if depth == 0:
            return at
    return len(text)


def struct_typedefs(text):
    """Names typedef'd to a struct or a union, which go by value only through a pointer."""
    names = set(re.findall(r"typedef\s+(?:struct|union)\s+\w+\s+(\w+)\s*;", text))
    for match in re.finditer(r"typedef\s+(?:struct|union)\b[^{;]*\{", text):
        end = closing(text, match.end() - 1, "{", "}")
        name = re.match(r"\s*(\w+)", text[end + 1:])
        if name:
            names.add(name.group(1))
    return names


def by_value(declaration, structs):
    """Whether a return type or parameter carries a 64-bit integer, floating point or a struct by value."""
    if "*" in declaration or "(" in declaration:
        return False
    plain = QUALIFIERS.sub(" ", declaration)
    return bool(BY_VALUE_TYPES.search(plain)) or any(word in structs for word in re.findall(r"\w+", plain))


def split_parameters(text):
    parameters, depth, start = [], 0, 0
    for at, char in enumerate(text):
        depth += {"(": 1, ")": -1}.get(char, 0)
        if char == "," and depth == 0:
            parameters.append(text[start:at])
            start = at + 1
    parameters.append(text[start:])
    return [parameter.strip() for parameter in parameters if parameter.strip() not in ("", "void", "...")]


def check_abi(imports, root):
    """Refuses an import whose declaration passes or returns what the console's code doesn't take as GCC passes it."""
    text = declarations_text(root)
    structs = struct_typedefs(text)
    problems = []
    for entry in imports:
        if entry["variable"]:
            continue
        match = re.search(rf"([^;{{}}#]*?)\b{entry['name']}\s*\(", text)
        if not match:
            problems.append(f"{entry['name']}: no declaration in include/xsdk or src to check")
            continue
        end = closing(text, match.end() - 1, "(", ")")
        returns = match.group(1).split("\n")[-1]
        if by_value(returns, structs):
            problems.append(f"{entry['name']}: returns {returns.strip()} by value")
        for parameter in split_parameters(text[match.end():end]):
            if by_value(parameter, structs):
                problems.append(f"{entry['name']}: takes {parameter} by value")
    if problems:
        sys.exit("gen_imports: these imports need a stub that converts between GCC's and the console's conventions, "
                 "which none does yet; pass them by pointer:\n  " + "\n  ".join(problems))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--list", action="store_true", help="print the import names instead of generating files")
    parser.add_argument("table", type=Path, help="imports/imports.txt")
    parser.add_argument("output", type=Path, nargs="?", help="directory for the generated .S files")
    args = parser.parse_args()

    imports = parse_imports(args.table)
    if args.list:
        print(" ".join(entry["name"] for entry in imports))
        return
    if args.output is None:
        parser.error("output directory required")
    check_abi(imports, args.table.resolve().parent.parent)
    args.output.mkdir(parents=True, exist_ok=True)
    for entry in imports:
        path = args.output / f"{entry['name']}.S"
        text = generate(entry)
        if not path.exists() or path.read_text() != text:
            path.write_text(text, newline="\n")


if __name__ == "__main__":
    main()
