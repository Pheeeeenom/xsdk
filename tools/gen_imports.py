#!/usr/bin/env python3
"""Generate one assembly file per kernel or XAM import listed in imports/imports.txt."""

import argparse
import sys
from pathlib import Path

LIBRARY_NAME_BYTES = 16

# A record's top byte is its type and its low 16 bits its ordinal (xenia:src/xenia/cpu/xex_module.cc:1133-1134).
RECORD_VARIABLE = 0x00000000
RECORD_THUNK = 0x01000000
# A working XDK-built title's thunks repeat the record in word 1 with type 2 (user's console files).
RECORD_THUNK_SECOND = 0x02000000


def parse_imports(path):
    imports = []
    for line_number, line in enumerate(path.read_text().splitlines(), 1):
        fields = line.split("#", 1)[0].split()
        if not fields:
            continue
        if len(fields) not in (3, 4) or (len(fields) == 4 and fields[3] != "variable"):
            sys.exit(f"{path}:{line_number}: expected library, ordinal and name, then \"variable\" for a variable")
        library, ordinal, name = fields[:3]
        if len(library) >= LIBRARY_NAME_BYTES:
            sys.exit(f"{path}:{line_number}: library name {library} is too long")
        imports.append({
            "library": library,
            "ordinal": int(ordinal, 16),
            "name": name,
            "variable": len(fields) == 4,
        })
    return imports


def library_name_directive(library):
    padding = "\\0" * (LIBRARY_NAME_BYTES - len(library))
    return f'\t.ascii\t"{library}{padding}"'


def import_record(slot, thunk, entry):
    return [
        "// elf2xex reads these records to build the import libraries header.",
        "\t.section .xsdk.imports, \"\"",
        f"\t.long\t{slot}",
        f"\t.long\t{thunk}",
        f"\t.long\t{entry['ordinal']:#x}",
        "\t.long\t0",
        library_name_directive(entry["library"]),
        "",
    ]


def header(entry):
    return f"// Generated by tools/gen_imports.py from imports/imports.txt: {entry['library']} ordinal " \
        f"{entry['ordinal']:#05x}."


# A variable gets no thunk: the loader writes its address into the record (xenia:src/xenia/cpu/xex_module.cc:1173).
def generate_variable(entry):
    name = entry["name"]
    lines = [
        header(entry),
        "",
        f"\t.section .rodata.xsdk_imp_{name}, \"a\"",
        "\t.balign 4",
        f"\t.globl\t{name}",
        f"\t.type\t{name}, @object",
        f"{name}:",
        f"\t.long\t{RECORD_VARIABLE | entry['ordinal']:#010x}",
        f"\t.size\t{name}, 4",
        "",
        *import_record(name, 0, entry),
    ]
    return "\n".join(lines)


# A function is its thunk, as in the console's own titles: GCC calls by the console's convention (-mcall-xsdk), so
# the export takes the caller's registers and stack slots as they are.
def generate(entry):
    if entry["variable"]:
        return generate_variable(entry)
    name = entry["name"]
    ordinal = entry["ordinal"]
    lines = [
        header(entry),
        "",
        f"\t.section .rodata.xsdk_imp_{name}, \"a\"",
        "\t.balign 4",
        f"\t.globl\txsdk_imp_{name}",
        f"xsdk_imp_{name}:",
        f"\t.long\t{RECORD_VARIABLE | ordinal:#010x}",
        "",
        f"\t.section .text.xsdk_thunk_{name}, \"ax\"",
        "\t.balign 16",
        "// The loader rewrites the first two words to load the export's address into r11.",
        f"\t.globl\t{name}",
        f"\t.type\t{name}, @function",
        f"{name}:",
        f"\t.long\t{RECORD_THUNK | ordinal:#010x}",
        f"\t.long\t{RECORD_THUNK_SECOND | ordinal:#010x}",
        "\tmtctr\tr11",
        "\tbctr",
        f"\t.size\t{name}, . - {name}",
        "",
        *import_record(f"xsdk_imp_{name}", name, entry),
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--list", action="store_true", help="print the import names instead of generating files")
    parser.add_argument("table", type=Path, help="imports/imports.txt")
    parser.add_argument("output", type=Path, nargs="?", help="directory for the generated .S files")
    args = parser.parse_args()

    imports = parse_imports(args.table)
    if args.list:
        print(" ".join(entry["name"] for entry in imports))
        return
    if args.output is None:
        parser.error("output directory required")
    args.output.mkdir(parents=True, exist_ok=True)
    for entry in imports:
        path = args.output / f"{entry['name']}.S"
        text = generate(entry)
        if not path.exists() or path.read_text() != text:
            path.write_text(text, newline="\n")


if __name__ == "__main__":
    main()
