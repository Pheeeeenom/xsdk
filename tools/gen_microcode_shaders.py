#!/usr/bin/env python3
"""Generate milestone 25's pixel shader container, which xsdk_test loads 200 times to fill shared microcode pages.

The shader writes one float constant, c0, as the colour. xsdk_test makes 200 shaders from it, each reading a constant
of its own: it rewrites the export's source registers, in the instruction's third dword (src1_reg in bits 16-23 and
src2_reg in bits 8-15, xenia:src/xenia/gpu/ucode.h AluInstruction), so each shader's microcode differs from the next,
and two sharing a block would draw one another's colour. Its microcode is a control-flow pair and one instruction,
24 bytes, so each takes one 256-byte block.

Packed as in tools/gen_triangle_shaders.py, from Xenia's instruction definitions through xost's encoders and container
emitter, and checked against xost's text assembler. Prints a C header with the container and where its source
registers sit, then its disassembly on stderr.
"""

import struct
import sys

import gen_triangle_shaders as tri
from gen_triangle_shaders import ce, container, enc, xu
from xasm import textasm

COLOR_CONSTANT = 0
# The export is the first instruction, after the one control-flow pair.
EXPORT_SLOT = 1
SLOT_DWORDS = 3
SOURCE_DWORD_IN_SLOT = 2
SRC1_SHIFT = 16
SRC2_SHIFT = 8
PIXEL_SHADER_TEXT = """
alloc colors
exece
max oC0, c0, c0
"""


def pixel_shader(constant):
    export = enc.build_alu(vector_opcode=xu.AluVectorOpcode.kMax, vector_dest=tri.EXPORT_COLOR_0,
        vector_write_mask=tri.WRITE_XYZW, is_export=True, src1_reg=constant, src1_is_temp=False,
        src2_reg=constant, src2_is_temp=False, src3_is_temp=True)
    dwords = tri.pack([enc.build_cf_alloc(alloc_type=tri.ALLOC_COLORS), tri.execute(EXPORT_SLOT, 1, end=True)],
        [export])
    ucode = struct.pack(f">{len(dwords)}I", *dwords)
    if textasm.assemble_text(PIXEL_SHADER_TEXT.replace("c0", f"c{constant}"), "pixel") != ucode:
        sys.exit("gen_microcode_shaders: the pixel shader differs from xost's assembly of it")
    return ce.build_container(
        "pixel", ucode, constants=[],
        program_control=tri.program_control(ps_num_reg=0, ps_export_mode=tri.PS_EXPORT_MODE_COLOR),
        context_misc=tri.CONTEXT_MISC_CENTROIDS_AND_CENTERS,
        interpolators=[ce.Interpolator(tri.EXPORT_INTERPOLATOR_0, ce.USAGE_COLOR, 0)],
        ps_field18=tri.PS_INTERPOLATOR_WORD, creator=tri.CREATOR), ucode


def patched(words, source_dword, constant):
    """The template with its source registers rewritten, as xsdk_test makes each shader."""
    out = list(words)
    fields = 0xFF << SRC1_SHIFT | 0xFF << SRC2_SHIFT
    out[source_dword] = (out[source_dword] & ~fields) | constant << SRC1_SHIFT | constant << SRC2_SHIFT
    return out


def main():
    blob, ucode = pixel_shader(COLOR_CONSTANT)
    microcode_dword = blob.index(ucode) // 4
    source_dword = microcode_dword + EXPORT_SLOT * SLOT_DWORDS + SOURCE_DWORD_IN_SLOT
    words = struct.unpack(f">{len(blob) // 4}I", blob)
    # Rewriting the fields must give what the encoder gives for another constant.
    for constant in (1, 199):
        other, _ = pixel_shader(constant)
        if patched(words, source_dword, constant) != list(struct.unpack(f">{len(other) // 4}I", other)):
            sys.exit(f"gen_microcode_shaders: rewriting the source registers to c{constant} isn't the shader for it")
    print("#ifndef XSDK_MICROCODE_SHADERS_H\n#define XSDK_MICROCODE_SHADERS_H\n\n#include <stdint.h>\n")
    print("// Generated by tools/gen_microcode_shaders.py.")
    tri.print_array("microcode_pixel_shader", blob)
    print("\n// The dword holding the export's source registers, and where each one's field starts.")
    print(f"enum {{ MICROCODE_SOURCE_DWORD = {source_dword}, MICROCODE_SRC1_SHIFT = {SRC1_SHIFT}, "
          f"MICROCODE_SRC2_SHIFT = {SRC2_SHIFT} }};")
    print("\n#endif")
    parsed = container.Container(blob)
    print("microcode_pixel_shader:", file=sys.stderr)
    print(xu.disassemble(parsed.ucode_dwords, parsed.shader_type), file=sys.stderr)


if __name__ == "__main__":
    main()
