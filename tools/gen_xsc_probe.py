#!/usr/bin/env python3
"""gen_xsc_probe.py <glsl_pack.c> <out.h> [refused.spv ...]: the programs for probe_xsc, the console probe of xost's
compiler in C (docs/scope/shader-compiling.md, step 2). From a pack Aurora's tools/build_glsl_pack.py wrote, each
program's SPIR-V with the container, literals and resources the PC made for it; then SPIR-V xost refuses, with the
message it gives on the PC.
"""
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "xenos-toolchain"))

import xsc.native as native  # noqa: E402

RESOURCE_KINDS = {"V4X_RESOURCE_PUSH_CONSTANTS": "XSDK_XSC_PUSH_CONSTANTS",
                  "V4X_RESOURCE_UNIFORM_BUFFER": "XSDK_XSC_UNIFORM_BUFFER", "V4X_RESOURCE_SAMPLER": "XSDK_XSC_SAMPLER"}
# xsdk's split, as the pack was built (vulkan4xenon:tools/build_shaders.py).
REGISTERS = 64
WORDS_A_LINE = 8


def words(body):
    return [int(w, 16) for w in re.findall(r"0x[0-9A-Fa-f]{1,8}", body)]


def word_lines(values):
    return ",\n".join("\t" + ", ".join(f"0x{w:08X}" for w in values[i:i + WORDS_A_LINE])
                      for i in range(0, len(values), WORDS_A_LINE))


def programs(pack_text):
    spirv = {n: words(b) for n, b in re.findall(r"const uint32_t (glsl_\w+)_spirv\[\] = \{([^}]*)\};", pack_text)}
    containers = {n: words(b) for n, b in
                  re.findall(r"static const uint32_t (glsl_\w+)_container\[\] = \{([^}]*)\};", pack_text)}
    literals = {n: re.findall(r"\{ (\d+), \{ ([^}]*) \} \}", b) for n, b in
                re.findall(r"static const V4xShaderLiteral (glsl_\w+)_literals\[\] = \{(.*?)\n\};", pack_text, re.S)}
    resources = {n: re.findall(r"\{ (V4X_RESOURCE_\w+), (\d+), (\d+), (\d+), (\d+) \}", b) for n, b in
                 re.findall(r"static const V4xShaderResource (glsl_\w+)_resources\[\] = \{(.*?)\n\};", pack_text,
                            re.S)}
    for name in sorted(spirv):
        yield name, spirv[name], containers[name], literals.get(name, []), resources.get(name, [])


def refusal(path):
    blob = path.read_bytes()
    try:
        native.compile_spirv(blob, REGISTERS, REGISTERS, True)
    except native.CompileError as e:
        if e.status == native.REFUSED:
            return list(struct.unpack(f"<{len(blob) // 4}I", blob)), str(e)
    sys.exit(f"{path}: xost doesn't refuse it")


def c_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    pack, out = Path(sys.argv[1]), Path(sys.argv[2])
    text = pack.read_text(encoding="utf-8")
    optimize = "--optimize" in text.splitlines()[0]
    lines = [f"// Generated by tools/gen_xsc_probe.py from {pack.name}; don't edit.", "",
             f"static const bool pack_optimized = {'true' if optimize else 'false'};", ""]
    table = []
    for i, (name, spirv, container, lits, res) in enumerate(programs(text)):
        lines += [f"static const uint32_t spirv_{i}[] = {{", word_lines(spirv), "};", "",
                  f"static const uint32_t container_{i}[] = {{", word_lines(container), "};", ""]
        if lits:
            lines += [f"static const ProbeLiteral literals_{i}[] = {{"]
            lines += [f"\t{{ {reg}, {{ {values} }} }}," for reg, values in lits] + ["};", ""]
        if res:
            lines += [f"static const XsdkXscResource resources_{i}[] = {{"]
            lines += [f"\t{{ {RESOURCE_KINDS[kind]}, {s}, {b}, {r}, {n} }}," for kind, s, b, r, n in res] + ["};", ""]
        table.append(f"\t{{ \"{name}\", spirv_{i}, {len(spirv)}, container_{i}, {len(container)}, "
                     f"{f'literals_{i}' if lits else 'NULL'}, {len(lits)}, {f'resources_{i}' if res else 'NULL'}, "
                     f"{len(res)} }},")
    lines += ["static const ProbeProgram programs[] = {"] + table + ["};", ""]
    refused = []
    for i, path in enumerate(Path(p) for p in sys.argv[3:]):
        spirv, message = refusal(path)
        lines += [f"static const uint32_t refused_{i}[] = {{", word_lines(spirv), "};", ""]
        refused.append(f"\t{{ \"{path.name}\", refused_{i}, {len(spirv)}, {c_string(message)} }},")
    lines += ["static const ProbeRefusal refusals[] = {"] + refused + ["};", ""]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
