#!/usr/bin/env python3
"""Generate the GPU draw cost probe's shaders (tests/probe_gpu_draw_cost.c, SCOPE.md milestone 39).

These are vkbench's cube shaders (vulkan4xenon:bench/shaders/):
- a matrix from push constants placing the cube;
- the texture times a tint 64 bytes into the push constants;
- the texture's luminance times the tint, the second program the shader-change variant switches to;
- the matrix alone and the tint alone, no texture, to see what the shaders' own work costs a draw.

Each GLSL source goes through xost's glslang to SPIR-V, then through xost's compiler at xsdk's register split with the
optimiser on, as titles' packs are built. Prints a C header with each container, its literals, and where its push
constants and sampler landed. Runs in WSL, where make builds the compiler for the PC; glslang is xost's Windows build,
which WSL runs.
"""

import struct
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "xenos-toolchain"))

import xsc.native as native  # noqa: E402

GLSLANG = ROOT / "xenos-toolchain" / "tools" / "glslang" / "bin" / "glslang.exe"
# xsdk's split (xsdk:src/gpu_setup.c).
REGISTERS = 64

SHADERS = (
    ("cube_vertex", "vert", """#version 450
layout(location = 0) in vec3 a_position;
layout(location = 1) in vec2 a_uv;
layout(location = 0) out vec2 v_uv;
layout(push_constant) uniform Push { mat4 mvp; } pc;

void main()
{
	gl_Position = pc.mvp * vec4(a_position, 1.0);
	v_uv = a_uv;
}
"""),
    ("cube_pixel", "frag", """#version 450
layout(location = 0) in vec2 v_uv;
layout(location = 0) out vec4 o_color;
layout(set = 0, binding = 0) uniform sampler2D u_texture;
layout(push_constant) uniform Push { layout(offset = 64) vec4 tint; } pc;

void main()
{
	o_color = texture(u_texture, v_uv) * pc.tint;
}
"""),
    ("cube_gray_pixel", "frag", """#version 450
layout(location = 0) in vec2 v_uv;
layout(location = 0) out vec4 o_color;
layout(set = 0, binding = 0) uniform sampler2D u_texture;
layout(push_constant) uniform Push { layout(offset = 64) vec4 tint; } pc;

void main()
{
	vec4 c = texture(u_texture, v_uv);
	float l = dot(c.rgb, vec3(0.299, 0.587, 0.114));
	o_color = vec4(l, l, l, c.a) * pc.tint;
}
"""),
    ("cube_plain_vertex", "vert", """#version 450
layout(location = 0) in vec3 a_position;
layout(push_constant) uniform Push { mat4 mvp; } pc;

void main()
{
	gl_Position = pc.mvp * vec4(a_position, 1.0);
}
"""),
    ("cube_flat_pixel", "frag", """#version 450
layout(location = 0) out vec4 o_color;
layout(push_constant) uniform Push { layout(offset = 64) vec4 tint; } pc;

void main()
{
	o_color = pc.tint;
}
"""),
)


def spirv_of(name, stage, source):
    with tempfile.TemporaryDirectory(dir=ROOT / "build") as directory:
        glsl = Path(directory) / f"{name}.{stage}"
        glsl.write_text(source)
        output = Path(directory) / f"{name}.spv"
        result = subprocess.run([str(GLSLANG), "-V", glsl.name, "-o", output.name], cwd=directory, capture_output=True,
                                text=True)
        if result.returncode != 0:
            sys.exit(f"glslang failed on {name}:\n{result.stdout}{result.stderr}")
        return output.read_bytes()


def print_words(name, words):
    print(f"static const uint32_t {name}[] = {{")
    for word in words:
        print(f"\t0x{word:08X},")
    print("};\n")


def main():
    print("#ifndef XSDK_DRAW_COST_SHADERS_H\n#define XSDK_DRAW_COST_SHADERS_H\n\n#include <stddef.h>\n#include <stdint.h>\n")
    print("// Generated by tools/gen_draw_cost_shaders.py.\n")
    print("// A literal the shader reads from a constant register, which the title writes.")
    print("typedef struct {\n\tuint32_t reg;\n\tfloat values[4];\n} DrawCostLiteral;\n")
    print("typedef struct {\n\tconst uint32_t *container;\n\tuint32_t container_bytes;\n"
          "\tconst DrawCostLiteral *literals;\n\tuint32_t literal_count;\n"
          "\t// The first register of the push constants, and the sampler's fetch constant; 0 if none.\n"
          "\tuint32_t push_register;\n\tuint32_t sampler;\n} DrawCostShader;\n")
    table = []
    for name, stage, source in SHADERS:
        container, manifest, resources = native.compile_spirv(spirv_of(name, stage, source), REGISTERS, REGISTERS,
                                                              optimize=True)
        print_words(f"{name}_container", struct.unpack(f">{len(container) // 4}I", container))
        literals = []
        for need in manifest:
            if len(need) != 2:
                sys.exit(f"{name}: a need other than a literal, {need!r}")
            literals.append(need)
        if literals:
            print(f"static const DrawCostLiteral {name}_literals[] = {{")
            for reg, values in literals:
                print(f"\t{{ {reg}, {{ {', '.join(repr(float(v)) + 'f' for v in values)} }} }},")
            print("};\n")
        push = [r for r in resources if r[0] == "push"]
        samplers = [r for r in resources if r[0] == "sampler"]
        if len(push) != 1 or len(samplers) > 1:
            sys.exit(f"{name}: expected one push block and at most one sampler, got {resources!r}")
        table.append(f"static const DrawCostShader {name} = {{ {name}_container, {len(container)}, "
                     f"{f'{name}_literals' if literals else 'NULL'}, {len(literals)}, {push[0][3]}, "
                     f"{samplers[0][3] if samplers else 0} }};")
    print("\n".join(table))
    print("\n#endif")


if __name__ == "__main__":
    main()
