#!/usr/bin/env python3
"""Generate milestone 31's pixel shader containers, for timing the pixel rate:
- fill_pixel_shader writes constant c0 in one instruction and reads no register;
- fill_unserialized_pixel_shader is the same with its alloc unserialized, and fill_two_pixel_shader takes the colour
  through a second instruction;
- sample_pixel_shader takes 4 samples at the interpolated coordinates, adds them and scales the sum by c0.

Both take tools/gen_texture_shaders.py's vertex shader, which passes texture coordinates in interpolator 0. Packed as in
tools/gen_triangle_shaders.py, from Xenia's instruction definitions (xenia:src/xenia/gpu/ucode.h) through xost's
encoders and container emitter, so each shader is fixed and known. Prints a C header with both containers, then their
disassembly on stderr.
"""

import struct
import sys

import gen_texture_shaders as tex
import gen_triangle_shaders as tri
from gen_triangle_shaders import ce, container, enc, xu

COLOR_CONSTANT = 0
COORDINATE_REGISTER = 0
SAMPLES = 4
# Two sequence bits an instruction: 1 marks a fetch, 2 waits for the fetches before (xenia:src/xenia/gpu/ucode.h:230).
SEQUENCE_FOUR_FETCHES = 0b01010101
SEQUENCE_SERIALIZE_FIRST = 0b10


def alu(opcode, dest, src1, src2, src1_is_temp=True, src2_is_temp=True, is_export=False):
    # An unused src3 stays a temporary, as xost's assembler encodes two-source instructions (xasm/textasm.py:45-63).
    return enc.build_alu(vector_opcode=opcode, vector_dest=dest, vector_write_mask=tri.WRITE_XYZW, is_export=is_export,
        src1_reg=src1, src1_is_temp=src1_is_temp, src2_reg=src2, src2_is_temp=src2_is_temp, src3_is_temp=True)


def pixel_container(dwords, last_register):
    return ce.build_container(
        "pixel", struct.pack(f">{len(dwords)}I", *dwords), constants=[],
        program_control=tri.program_control(ps_num_reg=last_register, ps_export_mode=tri.PS_EXPORT_MODE_COLOR),
        context_misc=tri.CONTEXT_MISC_CENTROIDS_AND_CENTERS,
        interpolators=[ce.Interpolator(tri.EXPORT_INTERPOLATOR_0, tex.USAGE_TEXCOORD, 0)],
        ps_field18=tri.PS_INTERPOLATOR_WORD, creator=tri.CREATOR)


def fill_pixel_shader(unserialized_alloc=False):
    # alloc colors; exece {max oC0, c0, c0}, from slot 1; unserialized as ucode.h:488 has it, if asked.
    export = alu(xu.AluVectorOpcode.kMax, tri.EXPORT_COLOR_0, COLOR_CONSTANT, COLOR_CONSTANT, src1_is_temp=False,
        src2_is_temp=False, is_export=True)
    alloc = enc.build_cf_alloc(alloc_type=tri.ALLOC_COLORS, is_unserialized=unserialized_alloc)
    return pixel_container(tri.pack([alloc, tri.execute(1, 1, end=True)], [export]), 0)


def fill_two_pixel_shader():
    # alloc colors; exece {max r0, c0, c0; max oC0, r0, r0}: the same colour through a second instruction.
    copy = alu(xu.AluVectorOpcode.kMax, 0, COLOR_CONSTANT, COLOR_CONSTANT, src1_is_temp=False, src2_is_temp=False)
    export = alu(xu.AluVectorOpcode.kMax, tri.EXPORT_COLOR_0, 0, 0, is_export=True)
    dwords = tri.pack([enc.build_cf_alloc(alloc_type=tri.ALLOC_COLORS), tri.execute(1, 2, end=True)], [copy, export])
    return pixel_container(dwords, 0)


def sample_pixel_shader():
    # exec {r1-r4 = texels at r0.xy}; exec {r1 = r1 + r2 + r3 + r4}; alloc colors; exece {oC0 = r1 * c0}; from slot 2.
    samples = [tex.sample(1 + i, COORDINATE_REGISTER) for i in range(SAMPLES)]
    sums = [alu(xu.AluVectorOpcode.kAdd, 1, 1, 2), alu(xu.AluVectorOpcode.kAdd, 3, 3, 4),
        alu(xu.AluVectorOpcode.kAdd, 1, 1, 3)]
    export = alu(xu.AluVectorOpcode.kMul, tri.EXPORT_COLOR_0, 1, COLOR_CONSTANT, src2_is_temp=False, is_export=True)
    control_flow = [
        tri.execute(2, SAMPLES, sequence=SEQUENCE_FOUR_FETCHES),
        tri.execute(2 + SAMPLES, len(sums), sequence=SEQUENCE_SERIALIZE_FIRST),
        enc.build_cf_alloc(alloc_type=tri.ALLOC_COLORS),
        tri.execute(2 + SAMPLES + len(sums), 1, end=True),
    ]
    return pixel_container(tri.pack(control_flow, samples + sums + [export]), SAMPLES)


# One word a line, as clang-format lays the array out.
def print_array(name, blob):
    words = struct.unpack(f">{len(blob) // 4}I", blob)
    print(f"static const uint32_t {name}[] = {{")
    for word in words:
        print(f"\t0x{word:08X},")
    print("};")


def main():
    print("#ifndef XSDK_FILL_SHADERS_H\n#define XSDK_FILL_SHADERS_H\n\n#include <stdint.h>\n")
    print("// Generated by tools/gen_fill_shaders.py.")
    shaders = (("fill_pixel_shader", fill_pixel_shader()), ("fill_unserialized_pixel_shader", fill_pixel_shader(True)),
        ("fill_two_pixel_shader", fill_two_pixel_shader()), ("sample_pixel_shader", sample_pixel_shader()))
    for name, blob in shaders:
        print_array(name, blob)
        parsed = container.Container(blob)
        print(f"{name}:", file=sys.stderr)
        print(xu.disassemble(parsed.ucode_dwords, parsed.shader_type), file=sys.stderr)
    print("\n#endif")


if __name__ == "__main__":
    main()
