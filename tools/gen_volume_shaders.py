#!/usr/bin/env python3
"""Generate xsdk_test's shaders for cube and 3D textures (tests/test_cube_volume.c): xost's containers for
vk_volume.vert, which passes a position and a coordinate on, and vk_cube.frag and vk_volume.frag, which sample a cube
in the coordinate's direction and a 3D texture at it, compiled on the PC at xsdk's register split, with the literals
each pools. Prints a C header. Runs in WSL, where make builds the compiler for the PC.
"""

import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "xenos-toolchain"))

import xsc.native as native  # noqa: E402

TESTDATA = ROOT / "xenos-toolchain" / "xsc" / "testdata"
SHADERS = (("volume_vertex_shader", "vk_volume.vert"), ("cube_pixel_shader", "vk_cube.frag"),
           ("volume_pixel_shader", "vk_volume.frag"))
# xsdk's split (xsdk:src/gpu_setup.c).
REGISTERS = 64


def print_words(name, words):
    print(f"static const uint32_t {name}[] = {{")
    for word in words:
        print(f"\t0x{word:08X},")
    print("};\n")


def print_literals(name, manifest):
    if not manifest:
        print(f"static const VolumeShaderLiteral *const {name}_literals = NULL;\n")
    else:
        print(f"static const VolumeShaderLiteral {name}_literals[] = {{")
        for reg, values in manifest:
            floats = ", ".join(f"{v!r}f" for v in values)
            print(f"\t{{ {reg}, {{ {floats} }} }},")
        print("};\n")
    print(f"enum {{ {name.upper()}_LITERALS = {len(manifest)} }};\n")


def main():
    print("#ifndef XSDK_VOLUME_SHADERS_H\n#define XSDK_VOLUME_SHADERS_H\n\n#include <stddef.h>\n#include <stdint.h>\n")
    print("// Generated by tools/gen_volume_shaders.py.\n")
    print("typedef struct {\n\tuint32_t reg;\n\tfloat values[4];\n} VolumeShaderLiteral;\n")
    for name, source in SHADERS:
        container, manifest, _ = native.compile_spirv((TESTDATA / f"{source}.spv").read_bytes(), REGISTERS, REGISTERS)
        print_words(name, struct.unpack(f">{len(container) // 4}I", container))
        print_literals(name, manifest)
    print("#endif")


if __name__ == "__main__":
    main()
