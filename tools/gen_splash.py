#!/usr/bin/env python3
"""Generate the splash screen's image: assets/vulkan4xenon.png as a palette and runs, for src/splash.c.

The PNG is decoded with the standard library alone (zlib and the five scanline filters of the PNG specification). Its
colours go in a palette, and its pixels in runs of one palette entry, left to right and top to bottom.
Prints a C header.
"""

import struct
import sys
import zlib

MAX_RUN = 0xFFFF
MAX_COLOURS = 0x10000


def read_png(path):
    with open(path, "rb") as f:
        data = f.read()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise SystemExit(f"{path}: not a PNG")
    pos = 8
    width = height = None
    compressed = b""
    while pos < len(data):
        length, kind = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + length]
        pos += 12 + length
        if kind == b"IHDR":
            width, height, depth, colour, _, _, interlace = struct.unpack(">IIBBBBB", body)
            if depth != 8 or colour not in (2, 6) or interlace:
                raise SystemExit(f"{path}: only 8-bit RGB or RGBA, not interlaced")
            channels = 3 if colour == 2 else 4
        elif kind == b"IDAT":
            compressed += body
        elif kind == b"IEND":
            break
    raw = zlib.decompress(compressed)
    stride = width * channels
    rows = []
    previous = bytearray(stride)
    for y in range(height):
        start = y * (stride + 1)
        kind = raw[start]
        line = bytearray(raw[start + 1:start + 1 + stride])
        for i in range(stride):
            left = line[i - channels] if i >= channels else 0
            up = previous[i]
            corner = previous[i - channels] if i >= channels else 0
            if kind == 1:
                line[i] = (line[i] + left) & 0xFF
            elif kind == 2:
                line[i] = (line[i] + up) & 0xFF
            elif kind == 3:
                line[i] = (line[i] + (left + up) // 2) & 0xFF
            elif kind == 4:
                estimate = left + up - corner
                distances = (abs(estimate - left), abs(estimate - up), abs(estimate - corner))
                nearest = (left, up, corner)[distances.index(min(distances))]
                line[i] = (line[i] + nearest) & 0xFF
        rows.append([tuple(line[x * channels:x * channels + 3]) for x in range(width)])
        previous = line
    return width, height, rows


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else "assets/vulkan4xenon.png"
    width, height, rows = read_png(path)
    palette = []
    index_of = {}
    runs = []
    for row in rows:
        for rgb in row:
            if rgb not in index_of:
                if len(palette) == MAX_COLOURS:
                    raise SystemExit(f"{path}: more than {MAX_COLOURS} colours")
                index_of[rgb] = len(palette)
                palette.append(rgb)
            index = index_of[rgb]
            if runs and runs[-1][0] == index and runs[-1][1] < MAX_RUN:
                runs[-1][1] += 1
            else:
                runs.append([index, 1])
    print("// Generated by tools/gen_splash.py from assets/vulkan4xenon.png; don't edit.")
    print("#include <stdint.h>")
    print()
    print(f"enum {{ SPLASH_WIDTH = {width}, SPLASH_HEIGHT = {height}, SPLASH_COLOURS = {len(palette)},"
          f" SPLASH_RUNS = {len(runs)} }};")
    print()
    print("// 0xRRGGBB.")
    print("static const uint32_t splash_palette[SPLASH_COLOURS] = {")
    for i in range(0, len(palette), 8):
        print("\t" + ", ".join(f"0x{r:02X}{g:02X}{b:02X}" for r, g, b in palette[i:i + 8]) + ",")
    print("};")
    print()
    print("// A palette entry in the top half, then how many pixels in a row take it.")
    print("static const uint32_t splash_runs[SPLASH_RUNS] = {")
    for i in range(0, len(runs), 8):
        print("\t" + ", ".join(f"0x{index:04X}{count:04X}" for index, count in runs[i:i + 8]) + ",")
    print("};")


if __name__ == "__main__":
    main()
